/** Цвет, которым браузер красит СВОЮ полосу над страницей на телефоне.
 *
 *  Значение обязано совпадать с `--bg` соответствующей темы, но взять его из
 *  токена нельзя: `<meta name="theme-color">` читается разборщиком HTML до
 *  всякого CSS, и переменная туда не доходит. Значит литерал — и значит вторая
 *  копия цвета, способная разойтись с палитрой молча. Расхождение ловит
 *  `theme.test.ts`: он читает сам `styles/tokens.css` и сверяет обе темы.
 *
 *  Без объявления полоса браузера в тёмной теме оставалась светлой над
 *  `#0E1420` — светлая рамка вокруг тёмной страницы. */
export const THEME_COLOR = {
  light: '#F4F6F9',
  dark: '#0E1420',
} as const;

export type ThemeColorScheme = keyof typeof THEME_COLOR;
