/** Сторона и переходы линии на фоне главной — бриф `70-workshop/specs/
 *  site-v3/05-line.md`, раздел 10, шаг 6 («Подключить реестр путей к
 *  странице»), поверх раздела 4.2 (Ч-4 «Акт»).
 *
 *  ЭТОТ ФАЙЛ БОЛЬШЕ НЕ РИСУЕТ ПУТИ. До этой правки здесь жили `runD`/
 *  `turnD`/`mirrorD` — вторая, независимая от `lib/linePaths.ts` генерация
 *  геометрии; страница брала `d` отсюда, а не из реестра, и реестр,
 *  нарисованный шагом 4, оставался мёртвым кодом («тест мерил реестр, а
 *  страница жила своей жизнью» — отчёт этого захода). Правка убирает
 *  вторую генерацию целиком: единственный источник `d` и `viewBox` каждого
 *  пути — `LINE_PATHS` (`lib/linePaths.ts`), и его читают `Section.astro` и
 *  `Footer.astro` напрямую.
 *
 *  Что остаётся здесь — это НЕ геометрия пути, а метаданные, из которых
 *  реестр рисовался руками и на которые всё ещё ссылается разметка
 *  (`data-line-side`/`data-line-turn`, раздел 4.3 брифа: «назначение по
 *  секциям» построено на этой самой стороне/переходе): сторона прогона
 *  каждой секции и наличие/направление перехода на её верхнем стыке,
 *  выведенные из Ч-4 (раздел 4.2) — правило акта, а не правило кривой.
 *
 *  Считается на сборке из `lib/sections.ts` — единственного источника
 *  состава секций и их актов. Второго списка секций, переходов или высот
 *  здесь не заводится: смени `act` у секции — и сторона, переходы и их
 *  число пересчитаются сами (а `lib/linePaths.ts` — отдельно, руками,
 *  раздел 10 шаг 4).
 */
import { HOME_SECTIONS, type HomeAct, type HomeSection } from './sections';

/* ───────────────────────── Единицы (раздел 4.1 брифа `05-line`) ────────
 *
 * `viewBox` каждого бокса линии — `0 0 1000 vbH`, где `vbH = round(1000 ·
 * H / 1180)`, 1180 — ширина контейнера (`--container`). При окне 1180 px
 * масштаб бокса РОВНО единый по обеим осям — обе оси используют один и
 * тот же контейнер знаменателем, не порознь для ширины и высоты. */
const CONTAINER_REF = 1180;

/** `vbH` бокса высотой `heightPx` (раздел 4.1). Округление — как в самой
 *  спеке (`Math.round`), тесты сверяют то же самое округление, второй
 *  формулы не заводится. */
export function computeVbH(heightPx: number): number {
  return Math.round((1000 * heightPx) / CONTAINER_REF);
}

/* ───────────────────────── Доки (раздел 4.2) ─────────────────────────── */
export const DOCK_LEFT = 59;
export const DOCK_RIGHT = 941;

/** Вынос концов пути за пределы `viewBox` (Г-2, раздел 3, п.2 брифа
 *  `05-line`: «≥ 60 единиц») — торец `stroke-linecap: round` прячется под
 *  соседний бокс, стык не виден. Экспортирован: `lib/linePaths.ts`
 *  (раздел 10, шаг 4) рисует каждый путь тем же выносом, второго числа не
 *  заводит. Путей этот файл больше не порождает — см. шапку файла. */
export const END_OVERHANG = 60;

export type LineSide = 'left' | 'right';
/** `'none'` — секция не владеет переходом на своём верхнем стыке;
 *  `'lr'` — переход слева направо; `'rl'` — переход справа налево. */
export type LineTurn = 'none' | 'lr' | 'rl';

export interface LineDatum {
  /** Сторона прогона ЭТОЙ секции — метаданные Ч-4, не геометрия: путь,
   *  который её исполняет, лежит в `LINE_PATHS[id]` (`lib/linePaths.ts`). */
  side: LineSide;
  /** Есть ли на ВЕРХНЕМ стыке этой секции переход, и в какую сторону
   *  (раздел 3.3: переход целиком принадлежит нижней секции — второго
   *  атрибута на секции-соседе сверху нет). Тоже метаданные: с шага 4
   *  переход — не отдельный бокс, а часть пути секции в `LINE_PATHS`
   *  (раздел 7.1 брифа: «элемента `.line-turn` больше нет»). */
  turn: LineTurn;
}

