  side: LineSide;
  /** Есть ли на ВЕРХНЕМ стыке этой секции переход, и в какую сторону
   *  (раздел 3.3: переход целиком принадлежит нижней секции — второго
   *  атрибута на секции-соседе сверху нет). Тоже метаданные: с шага 4
   *  переход — не отдельный бокс, а часть пути секции в `LINE_PATHS`
   *  (раздел 7.1 брифа: «элемента `.line-turn` больше нет»). */
