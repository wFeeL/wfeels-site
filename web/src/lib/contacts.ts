/** Прямой канал связи — один адрес на весь сайт.
 *
 *  До этого файла адрес был выписан строкой в трёх местах (форма, «спасибо»,
 *  подвал). Три копии одной строки расходятся ровно так же, как расходились
 *  списки путей: смена ника переписывается в двух местах из трёх, а третье
 *  ведёт в никуда и молчит — ссылка на чужой домен ничем не проверяется.
 */
export const TELEGRAM_URL = 'https://t.me/wfeels';

/** «@wfeels» — читаемый ник для текста («напишите в Telegram: @wfeels»,
 *  секция 11). Выводится из `TELEGRAM_URL`, а не хранится второй строкой:
 *  третьего места с этим адресом заводить нельзя (план `02-home-plan.md`,
 *  задача 12), а ник, вписанный рядом отдельным литералом, был бы им — просто
 *  без протокола и домена. */
export function telegramHandle(): string {
  return `@${TELEGRAM_URL.replace(/^https:\/\/t\.me\//, '')}`;
}

/** Почта — второй прямой канал (правка владельца 2026-08-13, «Контакты»,
 *  `10-offer/POSITIONING.md`). Тот же принцип, что у Telegram выше: один
 *  источник значения, второй копии строкой не заводится.
 *
 *  Экранированный вид не хранится отдельной константой: `emailHref`/
 *  `emailMarkup` считают его из `EMAIL` при каждом вызове, так что адрес
 *  физически не может разойтись сам с собой между ссылкой и подписью.
 */
export const EMAIL = 'githubwfeel@gmail.com';

/** «@» и «.» — числовыми ссылками (`&#64;`, `&#46;`), а не буквами. Простой
 *  сборщик почты читает СЫРОЙ HTML регуляркой вида `\S+@\S+\.\S+` и в этом
 *  тексте такой подстроки нет вовсе — символ `@` в разметке отсутствует,
 *  есть только его код. Браузер разворачивает числовую ссылку при разборе
 *  HTML (это работает и в тексте, и внутри атрибута `href`) ещё до того, как
 *  страница становится интерактивной, поэтому клик работает и без JS, а
 *  человек глазом видит обычный адрес — разворачивание делает сам HTML-
 *  парсер, а не какой-то скрипт на странице.
 */
function escapeAtDot(value: string): string {
  return value.replace(/@/g, '&#64;').replace(/\./g, '&#46;');
}

/** Готовая ссылка `<a href="mailto:…">` целиком, для вывода через `set:html`.
 *
 *  Обычная интерполяция Astro (`href={...}`) экранирует `&` в значениях
 *  атрибутов — числовая ссылка `&#64;` превращалась бы в `&amp;#64;` и
 *  переставала разворачиваться браузером обратно в «@» (проверено сборкой:
 *  `dist/index.html` нёс именно двойное экранирование, пока эта функция не
 *  стала отдавать тег целиком). `set:html` — единственный путь Astro вывести
 *  уже готовую разметку без второго прохода экранирования, а значит здесь
 *  должен быть собран весь тег сразу, а не только текст внутри него.
 *
 *  `<span class="link-label">` внутри — тот же приём, что у соседней ссылки
 *  Telegram (`home/Contact.astro`) и у ссылок подвала (`Footer.astro`,
 *  правка дизайн-ревью 2026-08-19): черта под ссылкой рисуется псевдо-
 *  элементом подписи и появляется только на `:hover`/`:focus-visible` — этот
 *  тег собирается строкой именно потому, что `set:html` не позволяет Astro
 *  дописать атрибут скоупа стилей, но класс `.link-label`, заданный здесь
 *  буквально, работает с родительским `:global(...)`-селектором так же, как
 *  на обычной разметке. */
export function emailLinkHtml(label: string): string {
  const enc = escapeAtDot(EMAIL);
  return `<a href="mailto:${enc}" rel="me"><span class="link-label">${label} · <strong>${enc}</strong></span></a>`;
}

/** Путь Material Design Icons «mail», набор `materialiconsoutlined`, 24px
 *  (`google/material-design-icons`, `src/communication/mail/
 *  materialiconsoutlined/24px.svg`) — тот же источник и лицензия (Apache
 *  License 2.0), что у остальных значков сайта (`home/ServiceIcon.astro`),
 *  этот комментарий — обязательство лицензии, не украшение. Родовой конверт,
 *  а не цветной логотип Gmail: у «Чертежа» один акцент на весь сайт и
 *  монохромные значки (тот же `TelegramMark.astro` рисует фирменный контур
 *  ОДНИМ `currentColor`, не брендовым синим) — четырёхцветная буква «M»
 *  ввела бы второй, третий и четвёртый цвет разом. */
const MAIL_ICON_SVG =
  '<svg viewBox="0 0 24 24" width="20" height="20" fill="currentColor" aria-hidden="true">' +
  '<path d="M20 4H4c-1.1 0-1.99.9-1.99 2L2 18c0 1.1.9 2 2 2h16c1.1 0 2-.9 2-2V6c0-1.1-.9-2-2-2zm0 4-8 5-8-5V6l8 5 8-5v2z"/>' +
  '</svg>';

/** Ссылка-значок на почту, готовая для `set:html` (та же причина, что у
 *  `emailLinkHtml` выше: обычная интерполяция Astro дважды экранировала бы
 *  числовые ссылки в `href`). У значка нет видимого текста — только
 *  доступное имя (`ariaLabel`), та же роль, что у `TelegramMark` в шапке и
 *  подвале. `className` необязателен: подвалу нужен свой класс размера цели
 *  нажатия, второму месту, если оно появится, он может не понадобиться. */
export function emailIconLinkHtml(ariaLabel: string, className?: string): string {
  const enc = escapeAtDot(EMAIL);
  const cls = className ? ` class="${className}"` : '';
  return `<a href="mailto:${enc}" rel="me"${cls} aria-label="${ariaLabel}">${MAIL_ICON_SVG}</a>`;
}

/** Ссылка-кнопка на почту: значок и подпись рядом, готовая для `set:html`
 *  (та же причина, что у `emailIconLinkHtml` выше — обычная интерполяция
 *  Astro дважды экранировала бы числовые ссылки в `href`). Нужна секции
 *  «Расскажите о задаче» (`home/Contact.astro`, задача 18): «Написать на
 *  почту» рядом с кнопкой «Написать в Telegram», а не голый значок подвала.
 *  Тот же `MAIL_ICON_SVG`, второго знака не рисуется. */
export function emailButtonHtml(label: string, className?: string): string {
  const enc = escapeAtDot(EMAIL);
  const cls = className ? ` class="${className}"` : '';
  return `<a href="mailto:${enc}" rel="me"${cls}>${MAIL_ICON_SVG}<span>${label}</span></a>`;
}
