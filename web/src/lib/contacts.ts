/** Прямой канал связи — один адрес на весь сайт.
 *
 *  До этого файла адрес был выписан строкой в трёх местах (форма, «спасибо»,
 *  подвал). Три копии одной строки расходятся ровно так же, как расходились
 *  списки путей: смена ника переписывается в двух местах из трёх, а третье
 *  ведёт в никуда и молчит — ссылка на чужой домен ничем не проверяется.
 */
export const TELEGRAM_URL = 'https://t.me/wfeels';

/** «@wfeels» — читаемый ник для текста («напишите в Telegram: @wfeels»,
 *  секция 11). Выводится из `TELEGRAM_URL`, а не хранится второй строкой:
 *  третьего места с этим адресом заводить нельзя (план `02-home-plan.md`,
 *  задача 12), а ник, вписанный рядом отдельным литералом, был бы им — просто
 *  без протокола и домена. */
export function telegramHandle(): string {
  return `@${TELEGRAM_URL.replace(/^https:\/\/t\.me\//, '')}`;
}
