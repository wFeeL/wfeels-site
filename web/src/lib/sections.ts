/** Акт «Трёх актов» (правка владельца 2026-08-13, `70-workshop/specs/
 *  site-v3/02-background-line.md`, раздел 4.2): `'in'` — первый экран,
 *  `1` — «проблема» (pain), `2` — «дело» (services/pricing/cases),
 *  `3` — «доверие» (process/guarantees/about/faq), `'out'` — выход
 *  (contact). Читатель у поля теперь ОДИН — линия на фоне
 *  (`lib/backgroundLine.ts`, `computeActGroups`): отступы страницы из смены
 *  `act` больше не выводятся, правка владельца 2026-08-20 сделала зазор между
 *  секциями одинаковым на всех стыках (`pages/index.astro`, `GAP`). Второго
 *  перечня актов не заводится. */
export type HomeAct = 'in' | 1 | 2 | 3 | 'out';

export interface HomeSection {
  /** Якорь секции. Читает разметка (`id` на `<section>`), шапка и подвал
   *  (`lib/nav.ts` собирает из части этих якорей четыре пункта навигации) и
   *  рельс. */
  id: string;
  /** Порядковый номер секции на странице, 1..10 — только для отчётов и
   *  тестов; разметку он не определяет, порядок задаёт сам массив. */
  order: number;
  /** Заголовок-заглушка задачи 2. Взят дословно из названия секции в спеке
   *  02-home.md — это не выдуманный текст и не финальная копия: настоящие
   *  формулировки приходят отдельным проходом с владельцем (задача 1 плана) и
   *  заменяют эту строку секция за секцией в задачах 5–13. */
  title: string;
  /** Метка точки рельса, которой принадлежит секция. Словарь один на шапку и
   *  рельс (спека, раздел 3): `ЦЕНЫ`, а не `ПРАЙС`.
   *
   *  Русская метка. Английская — в `RAIL_LABELS_EN` ниже, отдельным полем не
   *  заводится: метка привязана к секции, а не к языку, и второе поле в этой
   *  же записи пришлось бы поддерживать глазами. */
  railLabel: string;
  /** Секция — первая в своей точке рельса. Точка рисуется рельсом (задача 4)
   *  один раз на группу, и это поле определяет, какая секция её представляет. */
  railFirst: boolean;
  /** Акт ритма «Три акта» — см. `HomeAct`. */
  act: HomeAct;
}

