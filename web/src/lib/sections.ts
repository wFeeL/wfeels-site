/** Единый список десяти секций главной — единственный источник, из
 *  которого читают разметка страницы, шапка (через `lib/nav.ts`) и рельс-
 *  скроллспай. Второй ручной перечень тех же секций разойдётся с этим молча —
 *  в этом репозитории список путей уже дважды расходился так.
 *
 *  Спека: `70-workshop/specs/site-v3/00-overview.md`, раздел 5 «Структура
 *  главной». Секция «Что можно проверить» снята правкой 2026-08-13 (D-030,
 *  бриф `02-case-illustrations.md`): её доказательства разошлись — «вес
 *  страницы» и «форма внизу» переехали в блок кейса «Этот сайт» (секция 5),
 *  «сколько занимает работа» переехало в «Что я гарантирую» (секция 7).
 *  Секций стало десять, точка рельса «КЕЙСЫ» больше не парная.
 *
 *    НАЧАЛО    — 1 первый экран
 *    КАК БЫВАЕТ — 2 как обычно бывает
 *    УСЛУГИ    — 3
 *    ЦЕНЫ      — 4
 *    КЕЙСЫ     — 5 кейсы
 *    ПРОЦЕСС   — 6 как я работаю
 *    ГАРАНТИИ  — 7 что я гарантирую
 *    ОБО МНЕ   — 8 обо мне
 *    FAQ   — 9 частые вопросы
 *    КОНТАКТ   — 10
 *
 *  Правка владельца 2026-08-18 (пункт 23 захода `03-redesign-2026-08-14`):
 *  `pain` и `faq` держали общую точку рельса с соседом («НАЧАЛО» и «ОБО
 *  МНЕ» соответственно) — восемь точек на десять секций. Владелец решил дать
 *  обеим свою точку: десять точек. Метки — короткие капслок-парафразы, тот
 *  же стиль, что у остальных («ГАРАНТИИ», не «ЧТО Я ГАРАНТИРУЮ»): «КАК БЫВАЕТ» —
 *  решение владельца 2026-08-18. Первым вариантом стояло «БОЛЬ», выведенное
 *  из метки секции на странице («ЗНАКОМАЯ БОЛЬ», `Pain.astro`, `PAIN_LABEL`),
 *  и оно было заменено по разбору дизайн-ревью: девять остальных меток
 *  отвечают на вопрос «что там», а «БОЛЬ» отвечала на «что ты почувствуешь»,
 *  то есть описывала читателя, а не раздел. Читатель этого сайта — владелец
 *  небольшого дела, а не маркетолог, и слова «боль» в навигации он не ищет, «FAQ» — слово владельца из пункта 23 («заголовок последней → FAQ»), не парафраз. Обе короче
 *  или равны длине существующих меток (`ГАРАНТИИ` — 8 знаков), проверено
 *  плейсхолдером рельса `.label { max-width: 96px }` (`Rail.astro`) — не
 *  ломают его на 390 px (см. отчёт исполнителя). */

export interface HomeSection {
  /** Якорь секции. Читает разметка (`id` на `<section>`), шапка и подвал
   *  (`lib/nav.ts` собирает из части этих якорей четыре пункта навигации) и
   *  рельс. */
  id: string;
  /** Порядковый номер секции на странице, 1..10 — только для отчётов и
   *  тестов; разметку он не определяет, порядок задаёт сам массив. */
  order: number;
  /** Заголовок-заглушка задачи 2. Взят дословно из названия секции в спеке
   *  02-home.md — это не выдуманный текст и не финальная копия: настоящие
   *  формулировки приходят отдельным проходом с владельцем (задача 1 плана) и
   *  заменяют эту строку секция за секцией в задачах 5–13. */
  title: string;
  /** Метка точки рельса, которой принадлежит секция. Словарь один на шапку и
   *  рельс (спека, раздел 3): `ЦЕНЫ`, а не `ПРАЙС`. */
  railLabel: string;
  /** Секция — первая в своей точке рельса. Точка рисуется рельсом (задача 4)
   *  один раз на группу, и это поле определяет, какая секция её представляет. */
  railFirst: boolean;
}

