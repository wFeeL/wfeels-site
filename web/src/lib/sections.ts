/** Единый список одиннадцати секций главной — единственный источник, из
 *  которого читают разметка страницы, шапка (через `lib/nav.ts`) и, начиная с
 *  задачи 4, рельс-скроллспай. Второй ручной перечень тех же секций разойдётся
 *  с этим молча — в этом репозитории список путей уже дважды расходился так.
 *
 *  Спека: `70-workshop/specs/site-v3/02-home.md`, раздел 3 «Каркас страницы и
 *  рельс». Таблица точек рельса ниже расходится с той спекой на одну строку
 *  намеренно: правка владельца 2026-08-13 расцепила секции 7 и 8 — раньше обе
 *  шли под меткой «ПРОЦЕСС», теперь у «Что я гарантирую» своя точка
 *  «ГАРАНТИИ». Спека ещё несёт старую таблицу (семь точек) — это её долг, не
 *  этого файла: `sections.ts`, а не спека, единственный источник, из которого
 *  читают шапка, подвал и рельс.
 *
 *    НАЧАЛО    — 1 первый экран + 2 как обычно бывает
 *    УСЛУГИ    — 3
 *    ЦЕНЫ      — 4
 *    КЕЙСЫ     — 5 кейсы + 6 что можно проверить
 *    ПРОЦЕСС   — 7 как я работаю
 *    ГАРАНТИИ  — 8 что я гарантирую
 *    ОБО МНЕ   — 9 обо мне + 10 частые вопросы
 *    КОНТАКТ   — 11
 */

export interface HomeSection {
  /** Якорь секции. Читает разметка (`id` на `<section>`), шапка и подвал
   *  (`lib/nav.ts` собирает из части этих якорей четыре пункта навигации) и,
   *  с задачи 4, рельс. */
  id: string;
  /** Порядковый номер секции на странице, 1..11 — только для отчётов и
   *  тестов; разметку он не определяет, порядок задаёт сам массив. */
  order: number;
  /** Заголовок-заглушка задачи 2. Взят дословно из названия секции в спеке
   *  02-home.md — это не выдуманный текст и не финальная копия: настоящие
   *  формулировки приходят отдельным проходом с владельцем (задача 1 плана) и
   *  заменяют эту строку секция за секцией в задачах 5–13. */
  title: string;
  /** Метка точки рельса, которой принадлежит секция. Словарь один на шапку и
   *  рельс (спека, раздел 3): `ЦЕНЫ`, а не `ПРАЙС`. */
  railLabel: string;
  /** Секция — первая в своей точке рельса. Точка рисуется рельсом (задача 4)
   *  один раз на группу, и это поле определяет, какая секция её представляет. */
  railFirst: boolean;
}

