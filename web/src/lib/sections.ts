/** Список якорей в порядке страницы. Читает `pages/index.astro`, чтобы не
 *  перечислять секции руками, и тесты, чтобы сверить разметку со списком. */
export function homeSectionIds(): string[] {
  return HOME_SECTIONS.map((s) => s.id);
}

/** Существует ли в списке секция с таким якорем. Используется там, где на
 *  секцию ссылаются по строке из другого места (`lib/nav.ts`) — чтобы
 *  переименованный в одном месте якорь падал тестом, а не молчал. */
export function hasHomeSection(id: string): boolean {
  return HOME_SECTIONS.some((s) => s.id === id);
}

/* ─────────────────────── Метки рельса по-английски ────────────────────────
 *
 * Ключ — тот же русский `railLabel`, что стоит в записи секции: он здесь
 * идентификатор точки, а не текст. Каждая метка обязана иметь пару, иначе
 * английский рельс покажет русское слово посреди английской страницы —
 * сборка падает.
 *
 * Метки короткие не для красоты: подпись активной точки живёт в полосе
 * `max-width: 96px` (`Rail.astro`, `.label`), моно 11 px с трекингом .16em —
 * примерно 8,4 px на знак, то есть около одиннадцати знаков. Самая длинная
 * английская метка — `GUARANTEES` (10). Русская `КАК БЫВАЕТ` (10) переведена
 * как `THE USUAL` (9), а не дословным `HOW IT GOES` (11): смысл тот же, а в
 * полосу она входит с запасом.
 *
 * `FAQ` одинаково на обоих языках — это слово владельца из пункта 23, а не
 * парафраз, и переводить его не во что. */
const RAIL_LABELS_EN: Readonly<Record<string, string>> = {
  'НАЧАЛО': 'START',
  'КАК БЫВАЕТ': 'THE USUAL',
  'УСЛУГИ': 'SERVICES',
  'ЦЕНЫ': 'PRICING',
  'КЕЙС': 'CASE',
  'ПРОЦЕСС': 'PROCESS',
  'ГАРАНТИИ': 'GUARANTEES',
  'ОБО МНЕ': 'ABOUT',
  'FAQ': 'FAQ',
  'КОНТАКТ': 'CONTACT',
};

for (const section of HOME_SECTIONS) {
  if (!RAIL_LABELS_EN[section.railLabel]) {
    throw new Error(
      `lib/sections.ts: у метки рельса «${section.railLabel}» нет английской пары. ` +
      'Английский рельс показал бы русское слово — молча, посреди английской страницы.',
    );
  }
}

/** Метка точки рельса на языке страницы. */
export function railLabel(section: HomeSection, locale: Locale): string {
  return locale === 'ru' ? section.railLabel : RAIL_LABELS_EN[section.railLabel];
}
