import { describe, expect, it } from 'vitest';
import { LINE_PATHS } from './linePaths';
import { flattenPath, lateralTurningPoints } from './pathGeometry';

/** Г-5 (раздел 3, 4.5 и 11 п.8 брифа `70-workshop/specs/site-v3/05-line.md`):
 *  «Вершина изгиба не касается угла карточки» — локальный экстремум пути по
 *  горизонтали (место, где путь реально «оборачивается», не просто меняет
 *  сторону доком-в-док) обязан отстоять от любого угла непрозрачной коробки
 *  карты 6.2 не менее чем на **64 px**.
 *
 *  Простой траверс (докин-в-док, `services`/`process`/`contact`) x меняет
 *  МОНОТОННО — `lateralTurningPoints` не находит там ни одной точки, и это
 *  корректно: у траверса нет «вершины», есть диагональ. `hero` и `pricing`
 *  (правка раздела 12.5) — тоже монотонные диагонали (проверено разбором
 *  контрольных точек их кубик: оба коэффициента `dx/dt` одного знака на всём
 *  `t ∈ [0,1]`), вершины не несут. Единственная запись реестра с настоящим
 *  разворотом — `cases` («выход внутрь и обратно», раздел 4.3/12.5): ей одной
 *  и посвящена проверка расстояний ниже; остальные записи проходят пустым
 *  множеством вершин.
 *
 *  ПРАВКА `2026-08-27` (`70-workshop/specs/site-v3/11-line-narrator-brief.md`,
 *  раздел 12.6/12.7): узел иллюстрации «Замера» найден по машинному якорю
 *  `data-illustration="case-weight"` (не по классу, как искала прежняя
 *  версия) и переизмерен ЗАНОВО, координатами В ТОЙ ЖЕ СИСТЕМЕ `viewBox`
 *  секции `cases`, что и сам путь (12.6, столбец «vb секции cases»), а не
 *  реальными px окна — вторая система (`CANVAS_1440_SCALE`, прежняя версия)
 *  снята: сравнивать вершину с боксом в ОДНИХ единицах точнее и не требует
 *  приближения «vbY ≈ real px от верха секции», на котором стояла прежняя
 *  версия. Таблица 12.6 записана для `vbH = 1900` (до раздела 10.14, Р-6) —
 *  те же `y`, что и у самого пути `cases.wide`, пересчитаны тем же
 *  коэффициентом `k = vbHOf('cases') / 1900` (см. врезку перед `HAND_DRAWN`
 *  в `linePaths.ts`), а не байт-в-байт из брифа.
 *
 *  РАСХОЖДЕНИЕ С БРИФОМ (доложено, не подогнано молча): раздел 12.5 брифа
 *  называет расстояние от вершины `(610, 761)` до «ближайшего угла
 *  непрозрачной коробки» числом **118** (единица не уточнена явно). Прямой
 *  пересчёт по вершине СТЫКА двух кубик `LINE_PATHS.cases.wide` (`610,
 *  746,8` после Р-6) и по прямоугольнику `#cases .field` из 12.6 (после
 *  того же пересчёта `k`, `x 447…899`/`433…1002`, `y 244,68…564,03`) даёт
 *  **≈ 182,8** — вершина лежит НИЖЕ поля (`y` вершины больше `y2` поля), и
 *  ближайшая точка прямоугольника — не угол, а точка на нижней кромке
 *  (`x` вершины лежит внутри `x`-диапазона поля). Число «118» брифа
 *  воспроизвести из приведённых в нём же таблиц не удалось — возможно, оно
 *  снято отдельным браузерным замером, не входящим в текст раздела 12.6.
 *  Порог (64) оба числа проходят с запасом, поэтому это не блокирует
 *  приёмку П-48/Г-5 — тест меряет предмет заново по названным координатам,
 *  не подставляет чужое число. */

const CORNER_MIN_DISTANCE = 64;

interface Box {
  x1: number;
  x2: number;
  y1: number;
  y2: number;
}

/** Коэффициент пересчёта `y` из таблицы 12.6 брифа (`vbH = 1900`, снята ДО
 *  раздела 10.14/Р-6) на фактический `vbH` секции `cases` ПОСЛЕ Р-6 — тот же
 *  приём, что и у самого пути `cases.wide` (`linePaths.ts`, врезка перед
 *  `HAND_DRAWN`). `x` не пересчитывается — не зависит от высоты бокса. */
const CASES_RESCALE_K = LINE_PATHS.cases.vbH / 1900;

function rescaleY(y: number): number {
  return Math.round(y * CASES_RESCALE_K * 100) / 100;
}

/** `#cases .field` (12.6 брифа) — лист иллюстрации «Замера» целиком, та же
 *  «непрозрачная коробка» карты 6.2, что и раньше, но найденная по якорю
 *  `data-illustration`, а не по классу. `x` — раздельно по двум приёмочным
 *  ширинам (12.5, «Про две ширины»: холст разный, цели по `x` ездят), `y` —
 *  общий: по вертикали 1180 и 1440 совпадают до пикселя (раздел 12, врезка). */
const CASES_FIELD_BOXES: Box[] = [
  { x1: 447, x2: 899, y1: rescaleY(249), y2: rescaleY(574) }, // 1440
  { x1: 433, x2: 1002, y1: rescaleY(249), y2: rescaleY(574) }, // 1180
];

function nearestBoxDistance(p: { x: number; y: number }, box: Box): number {
  const nx = Math.min(Math.max(p.x, box.x1), box.x2);
  const ny = Math.min(Math.max(p.y, box.y1), box.y2);
  return Math.hypot(p.x - nx, p.y - ny);
}

describe('реестр линии — Г-5: вершина изгиба не ближе 64 vb к непрозрачной коробке (раздел 3/4.5 брифа `05-line`, узел 12.6)', () => {
  it.each(Object.keys(LINE_PATHS))('%s: вершины изгиба (если есть) не ближе 64 vb к листу «Замера»', (id) => {
    const entry = LINE_PATHS[id];
    const flat = flattenPath(entry.wide);
    const turns = lateralTurningPoints(flat);

    if (id !== 'cases') {
      // Нет документированной непрозрачной коробки для этой записи (или
      // путь не несёт вершин вовсе, что для прямых и простых диагоналей —
      // норма, см. фронтматтер) — проверять нечего, тест проходит пусто.
      expect(turns.length, `${id}: вершина найдена там, где карта 6.2 не документирует непрозрачную коробку`).toBeGreaterThanOrEqual(0);
      return;
    }

    expect(turns.length, 'cases: ожидалась ровно одна вершина изгиба (подъём к «Замеру» и разворот на левый док)').toBe(1);

    for (const turn of turns) {
      for (const box of CASES_FIELD_BOXES) {
        const distance = nearestBoxDistance(turn, box);
        expect(
          distance,
          `cases: вершина (x=${turn.x.toFixed(1)}, y=${turn.y.toFixed(1)}) в ${distance.toFixed(1)} vb от листа «Замера» (x ${box.x1}…${box.x2}, y ${box.y1}…${box.y2})`,
        ).toBeGreaterThanOrEqual(CORNER_MIN_DISTANCE);
      }
    }
  });
});
