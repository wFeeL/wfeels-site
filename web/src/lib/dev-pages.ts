/** Входит ли служебная витрина `/dev/ui` в эту сборку.
 *
 *  Спека требует исключать витрину из сборки продакшена. Фактически её
 *  закрывали только `noindex` и правило в Caddy: та же сборка, выложенная на
 *  любую другую раздачу, показала бы служебную страницу наружу. Теперь маршрут
 *  просто не существует в боевой сборке — исключать нечего.
 *
 *  Почему флаг, а не `import.meta.env.PROD`: прогон e2e тоже собирает сайт
 *  (`astro build` + `preview`), и на витрине стоят проверки примитивов и полосы
 *  прогресса. Флаг ставит `playwright.config.ts`; боевая сборка его не ставит,
 *  и забыть снять его нельзя — по умолчанию витрины нет. */
export function devPagesEnabled(
  command: string,
  env: Record<string, string | undefined>,
): boolean {
  return command === 'dev' || env.DEV_PAGES === '1';
}
