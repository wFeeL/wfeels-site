import { localeFromPath, localeHome, stripLocale, type Locale } from '../i18n/locales';
import { hasHomeSection } from './sections';

export interface NavItem {
  href: string;
  text: string;
}

/** Якорь одной из одиннадцати секций главной → путь `/#якорь`. Проверяет, что
 *  секция с таким `id` действительно есть в `lib/sections.ts` — там теперь
 *  единственный источник якорей, и переименованный в одном месте якорь обязан
 *  падать здесь, а не молчать до продакшена. */
function anchor(locale: Locale, id: string, text: string): NavItem {
  if (!hasHomeSection(id)) {
    throw new Error(
      `lib/nav.ts: пункт «${text}» указывает на якорь #${id}, которого нет в ` +
      'lib/sections.ts — переименовали в одном месте и забыли второе.',
    );
  }
  /* Якорь берёт корень СВОЕЙ локали: `/#services` на русской версии,
     `/en#services` на английской. Пункт английской шапки, ведущий на `/#…`,
     уводил бы читателя на русскую главную — то есть менял бы язык страницы
     нажатием на пункт меню. Корень даёт `localeHome`, второй раз строка
     `/en` руками здесь не пишется. */
  const home = localeHome(locale);
  return { href: home === '/' ? `/#${id}` : `${home}#${id}`, text };
}

/** Разделы сайта. ОДИН список на шапку и на подвал.
 *
 *  Список живёт здесь, а не в разметке шапки, потому что перечень тех же путей
 *  во втором месте расходится молча: в этом репозитории так уже вышло дважды —
 *  со списком двуязычных путей и с исключениями из карты сайта. Подвал показывает
 *  ровно то же, что шапка, и доказывает это тестом «список разделов подвала
 *  совпадает со списком навигации шапки».
 *
 *  Пункты — якоря секций главной (спека 02, «Каркас страницы и рельс»), а не
 *  адреса отдельных страниц: `/pricing`, `/about` и подобные страницы не
 *  существуют и существовать не будут — эти темы стали секциями `/`. Путь
 *  вида `/#pricing` работает с любой страницы сайта: на главной браузер просто
 *  прокручивает без перезагрузки (путь совпадает с текущим), с посадочной —
 *  сначала переходит на главную, потом прокручивает. Это осознанная цена
 *  решения «пункты шапки — якоря» (спека, раздел 3): посетитель посадочной
 *  страницы, нажавший пункт меню, эту страницу покидает.
 *
 *  Пункт «Контакты» снят: кнопка «Обсудить задачу» ведёт туда же
 *  (`headerCtaHref` ниже) — второй элемент с той же целью читался бы как
 *  случайность, а не как решение.
 *
 *  Порядок общий, и в подвале он тот же, что в шапке: два разных порядка одних
 *  и тех же слов на одной странице читаются как два разных списка. */
const SECTIONS: Record<Locale, NavItem[]> = {
  ru: [
    anchor('ru', 'services', 'Услуги'),
    anchor('ru', 'pricing', 'Цены'),
    // С 2026-08-24 на главной три блока, поэтому заголовок, рельс и пункт
    // меню снова стоят во множественном числе.
    anchor('ru', 'cases', 'Кейсы'),
    anchor('ru', 'guarantees', 'Гарантии'),
    anchor('ru', 'about', 'Обо мне'),
  ],
  /* Английские разделы вернулись 2026-08-22 вместе с английской главной: те
     же пять якорей тех же пяти секций, только на своём корне (`/en#services`).
     Пусты они были ровно потому, что вести им было некуда — страницы `/en`
     не существовало, и пункт, который ничего не делает, обманывает сильнее
     отсутствующего. Теперь секции на `/en` есть все десять, и пункт ведёт
     туда же, куда его русская пара.

     Список НЕ второй перечень: подписи разные, а якоря те же самые строки
     `lib/sections.ts`, и `anchor()` роняет сборку, если якорь переименовали
     в одном месте и забыли во втором. */
  en: [
    anchor('en', 'services', 'Services'),
    anchor('en', 'pricing', 'Pricing'),
    anchor('en', 'cases', 'Case studies'),
    anchor('en', 'guarantees', 'Guarantees'),
    anchor('en', 'about', 'About'),
  ],
};

/* Пять пунктов на обоих языках, и это проверяется, а не подразумевается:
   шапка и подвал показывают ОДИН список (`sections()`), и потерянный при
   переводе пункт увёл бы английскую версию на четыре раздела молча. */
if (SECTIONS.ru.length !== SECTIONS.en.length) {
  throw new Error(
    `lib/nav.ts: разделов в шапке ${SECTIONS.ru.length} по-русски и ` +
    `${SECTIONS.en.length} по-английски. Английская версия — та же страница ` +
    'другими словами, а не другая навигация.',
  );
}
SECTIONS.ru.forEach((ru, i) => {
  const en = SECTIONS.en[i];
  const anchorOf = (item: NavItem) => item.href.split('#')[1];
  if (anchorOf(ru) !== anchorOf(en)) {
    throw new Error(
      `lib/nav.ts: пункт ${i + 1} ведёт на #${anchorOf(ru)} по-русски и на ` +
      `#${anchorOf(en)} по-английски — порядок разделов разошёлся между языками.`,
    );
  }
});

/** Разделы для языка страницы. Пустой список означает «группы разделов нет»:
 *  и шапка, и подвал обязаны в этом случае не рисовать пустой заголовок.
 *  Сегодня пустым он не бывает ни на одном языке — но условие в разметке
 *  остаётся: оно дешевле, чем разбирательство в день, когда список снова
 *  опустеет. */
export function sections(lang: Locale): NavItem[] {
  return SECTIONS[lang];
}

/** Адрес страницы контактов — цель кнопки шапки на РУССКИХ страницах везде,
 *  кроме главной. Одно место на весь сайт: сама кнопка, `CTA_HIDDEN_ON` ниже
 *  и `headerCtaHref` читают отсюда.
 *
 *  Правка 2026-08-26 (задача Б-2, дефект «кнопка подвала английских страниц
 *  вела на русскую форму»): у английской версии контакта по-прежнему нет
 *  (`BILINGUAL_PATHS` в `i18n/locales.ts` перечисляет только `/`), но она
 *  больше и не нужна — на `/en` стоят те же десять секций, что на `/`
 *  (`components/home/HomePage.astro`), и форма живёт там же, под якорем
 *  `#contact`. Поэтому английская ветка `headerCtaHref` ниже ведёт на
 *  `${localeHome('en')}#contact`, а НЕ сюда: эта константа с задачи Б-2
 *  отвечает только за русский адрес и больше не служит запасным вариантом
 *  для английских страниц (им запасной вариант больше не нужен). */
export const HEADER_CTA_HREF = '/contact';

/** Страницы, на которых кнопка в шапке не рисуется.
 *
 *  `/contact` — кнопка звала бы туда, где человек уже стоит, и спорила по весу
 *  с «Отправить»: две одинаковые основные кнопки в одном экране.
 *  `/thanks` — там она становилась самым громким элементом и звала отправить
 *  заявку заново, хотя осмысленное действие после отправки — уйти на главную. */
const CTA_HIDDEN_ON = [HEADER_CTA_HREF, '/thanks'];

/** Путь без якоря, строки запроса и хвостового слэша. */
export function normalizePath(value: string): string {
  const path = value.split('#')[0].split('?')[0];
  return path.replace(/\/+$/, '') || '/';
}

/** Ссылка ведёт на страницу, которая уже открыта.
 *
 *  Ссылка с якорем не считается совпадением никогда. До этой задачи у шапки
 *  был один пункт-якорь («Контакты» на английской странице) и четыре пункта —
 *  адреса страниц; теперь все пункты шапки — якоря секций главной
 *  (`lib/sections.ts`). Ничего не изменилось бы, отметь `samePath` якорь как
 *  совпадение: по одному только пути `/` все четыре пункта разом получили бы
 *  `aria-current`, и отметка перестала бы что-либо значить. Текущий раздел
 *  теперь показывает только рельс (задача 4) — в шапке `aria-current` не
 *  появляется вовсе, и это ожидаемое поведение, а не пробел. НЕ «чинить» эту
 *  функцию ради возврата отметки в шапку — правка сломает рельс и вернёт баг,
 *  ради которого функция и написана. */
export function samePath(href: string, pathname: string): boolean {
  if (href.includes('#')) return false;
  return normalizePath(href) === normalizePath(pathname);
}

/** Рисовать ли кнопку в шапке на этом пути.
 *
 *  Решение принимает шапка по адресу страницы, а не каждая страница свойством:
 *  иначе новая страница обязана была бы про кнопку помнить, а забытое свойство
 *  провалилось бы молча. Список выше — единственное место правки. */
export function showHeaderCta(pathname: string): boolean {
  return !CTA_HIDDEN_ON.includes(stripLocale(normalizePath(pathname)));
}

/** Пути, у которых есть собственная форма заявки вплотную над подвалом —
 *  главная (секция «Контакт»), сама `/contact` и посадочные услуг (секция
 *  «ЗАЯВКА», `pages/services/[slug].astro`). Полоса действия подвала там
 *  дублировала бы кнопку рядом с работающей формой и уводила бы от неё —
 *  спека `70-workshop/specs/site-v3/09-footer-brief.md`, раздел 3.2. */
const FOOTER_CTA_HIDDEN_EXACT = ['/', '/contact', '/thanks'];
const SERVICE_LANDING = /^\/services\/[^/]+$/;

/** Рисовать ли полосу действия `.footer-cta` в подвале на этом пути.
 *
 *  Решение — то же самое, что `showHeaderCta`, но для другого конца
 *  страницы: чистая функция пути, а не свойство, которое задаёт каждая
 *  страница руками (спека 09, раздел 3.1). `Base.astro` пробрасывает
 *  результат в `<Footer cta={…} />`; `Footer.astro` держит `cta` как проп
 *  для случая, когда адрес и содержание страницы разойдутся намеренно.
 *
 *  Правило (раздел 3.1, признак — «есть ли у страницы своя форма заявки»):
 *  - `/`, `/contact` — на странице стоит собственная форма (секция
 *    «Контакт» / сама форма) вплотную к месту, где встала бы полоса;
 *  - `/thanks` — форма уже отправлена, повторный призыв читается как «мы
 *    её потеряли» (раздел 3.3, отдельная причина от первых двух);
 *  - `/services/<slug>` — посадочная услуги, у неё секция «ЗАЯВКА» с
 *    `LeadForm` вплотную над подвалом (раздел 3.2); `/services` — каталог,
 *    под исключение не подпадает, полоса у него есть.
 *
 *  Локаль снимается тем же способом, что у `showHeaderCta`: `/en/thanks` и
 *  `/en` считаются как их русские пары, а `/en/privacy` и подобные —
 *  как обычная страница (раздел 3.2, «/en несёт ту же разметку, что и
 *  главная», а не отдельный список путей). */
export function showFooterCta(pathname: string): boolean {
  const path = stripLocale(normalizePath(pathname));
  if (FOOTER_CTA_HIDDEN_EXACT.includes(path)) return false;
  if (SERVICE_LANDING.test(path)) return false;
  return true;
}

/** Куда ведёт кнопка «Обсудить задачу» (шапка) и «Написать»/полоса действия
 *  (подвал, `Footer.astro`) — ОДНО правило на обе, живёт здесь же, где
 *  решение «рисовать кнопку или нет» (`showHeaderCta`), а не в разметке
 *  страниц или компонентов: новой странице и новому месту кнопки не придётся
 *  ничего про это помнить. До задачи Б-2 (2026-08-26) подвал читал не эту
 *  функцию, а константу `HEADER_CTA_HREF` напрямую — тем самым обходил
 *  правило про язык страницы, и кнопка полосы действия на английских
 *  страницах вела на русский `/contact`, пока рядом стоящая ссылка тела вела
 *  на `${localeHome('en')}#contact` верно. Общая функция для двух мест —
 *  решение, а не заведённый рядом второй «headerCtaHref для подвала»:
 *  правило одно и по смыслу, и по коду.
 *
 *  На главной СВОЕГО ЯЗЫКА секция контакта лежит на этой же странице — кнопка
 *  ведёт на якорь `#contact` и прокручивает без перезагрузки. Локаль с пути
 *  снимается (`stripLocale`) для сравнения с корнем — правка 2026-08-22: до
 *  неё проверялся точный путь `/`, потому что у английской главной секций не
 *  было вовсе и якорь `#contact` вёл бы в пустоту; теперь `/en` несёт те же
 *  десять секций, что `/`.
 *
 *  На любой другой русской странице кнопка ведёт на `/contact`
 *  (`HEADER_CTA_HREF`) — своя страница с формой существует.
 *
 *  На любой другой АНГЛИЙСКОЙ странице (`/en/privacy`, `/en/terms`,
 *  `/en/consent`, `/en/404`, …) английской страницы контакта по-прежнему нет
 *  (`hasTranslation('/contact')` — `false`), но она и не нужна: форма живёт
 *  на `/en` под тем же якорем `#contact`, что и на главной. Кнопка ведёт туда
 *  — `${localeHome('en')}#contact`, то есть `/en#contact` — а не на русский
 *  `/contact`: с этой задачи ни одна английская страница не ведёт на адрес
 *  без языкового префикса (сторож — `tests/dist-footer-lang-links.test.ts`).
 *  `HEADER_CTA_HREF` для английской ветки поэтому больше не читается вовсе. */
export function headerCtaHref(pathname: string): string {
  const path = stripLocale(normalizePath(pathname));
  if (path === '/') return '#contact';
  return localeFromPath(pathname) === 'en' ? `${localeHome('en')}#contact` : HEADER_CTA_HREF;
}
