import { stripLocale, type Locale } from '../i18n/locales';

export interface NavItem {
  href: string;
  text: string;
}

/** Разделы сайта. ОДИН список на шапку и на подвал.
 *
 *  Список живёт здесь, а не в разметке шапки, потому что перечень тех же путей
 *  во втором месте расходится молча: в этом репозитории так уже вышло дважды —
 *  со списком двуязычных путей и с исключениями из карты сайта. Подвал показывает
 *  ровно то же, что шапка, и доказывает это тестом «список разделов подвала
 *  совпадает со списком навигации шапки».
 *
 *  Ближайшая правка отсюда — снятие четырёх пунктов, которые сегодня ведут в
 *  404 (`/services`, `/cases`, `/pricing`, `/about`): перед публикацией это
 *  одна правка в одном месте, а не две в двух.
 *
 *  Порядок общий, и в подвале он тот же, что в шапке: два разных порядка одних
 *  и тех же пяти слов на одной странице читаются как два разных списка. */
const SECTIONS: Record<Locale, NavItem[]> = {
  ru: [
    { href: '/services', text: 'Услуги' },
    { href: '/cases', text: 'Кейсы' },
    { href: '/pricing', text: 'Цены' },
    { href: '/contact', text: 'Контакты' },
    { href: '/about', text: 'Обо мне' },
  ],
  /* Английских разделов не существует: их приносит спека 02 вместе с английским
     ядром. До правки в шапке стояли пять пунктов на `/en/#services` и подобные —
     на странице таких мест нет, и нажатие не делало ничего: ни перехода, ни
     прокрутки, ни честной 404. Пункт, который ничего не делает, обманывает
     сильнее отсутствующего: посетитель считает раздел существующим и решает, что
     сломан сайт. Разделы вернутся сюда вместе со страницами, на которые им
     вести, — и появятся сразу и в шапке, и в подвале. */
  en: [],
};

/** Разделы для языка страницы. Пустой список означает «группы разделов нет»:
 *  и шапка, и подвал обязаны в этом случае не рисовать пустой заголовок. */
export function sections(lang: Locale): NavItem[] {
  return SECTIONS[lang];
}

/** Адрес, куда ведёт кнопка в шапке. Одно место на весь сайт: и сама кнопка,
 *  и правило «не показывать её там, где она никуда не ведёт» читают отсюда.
 *
 *  Адрес ОДИН на обе локали, и это осознанно, а не забыто. На английских
 *  страницах кнопка подписана по-английски, а ведёт на русский `/contact`:
 *  английской версии контакта не существует (`BILINGUAL_PATHS` в
 *  `i18n/locales.ts` перечисляет только `/`), и `/en/contact` был бы 404.
 *  Смена языка страницы посреди пути хуже пустой страницы, но лучше ошибки.
 *
 *  Когда английский контакт появится, адрес обязан начать зависеть от локали —
 *  иначе английский посетитель так и будет уходить на русскую форму. Тогда сюда
 *  вместо константы встанет функция от локали, а `CTA_HIDDEN_ON` ниже уже
 *  готово: оно сравнивает пути без языкового префикса. */
export const HEADER_CTA_HREF = '/contact';

/** Страницы, на которых кнопка в шапке не рисуется.
 *
 *  `/contact` — кнопка звала бы туда, где человек уже стоит, и спорила по весу
 *  с «Отправить»: две одинаковые основные кнопки в одном экране.
 *  `/thanks` — там она становилась самым громким элементом и звала отправить
 *  заявку заново, хотя осмысленное действие после отправки — уйти на главную. */
const CTA_HIDDEN_ON = [HEADER_CTA_HREF, '/thanks'];

/** Путь без якоря, строки запроса и хвостового слэша. */
export function normalizePath(value: string): string {
  const path = value.split('#')[0].split('?')[0];
  return path.replace(/\/+$/, '') || '/';
}

/** Ссылка ведёт на страницу, которая уже открыта.
 *
 *  Ссылка с якорем не считается совпадением никогда: пункты английской
 *  навигации указывают на секции одной страницы (`/en/#services`), и по
 *  одному только пути все пять разом получили бы `aria-current`. */
export function samePath(href: string, pathname: string): boolean {
  if (href.includes('#')) return false;
  return normalizePath(href) === normalizePath(pathname);
}

/** Рисовать ли кнопку в шапке на этом пути.
 *
 *  Решение принимает шапка по адресу страницы, а не каждая страница свойством:
 *  иначе новая страница обязана была бы про кнопку помнить, а забытое свойство
 *  провалилось бы молча. Список выше — единственное место правки. */
export function showHeaderCta(pathname: string): boolean {
  return !CTA_HIDDEN_ON.includes(stripLocale(normalizePath(pathname)));
}
