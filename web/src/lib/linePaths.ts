/** Реестр путей линии на фоне главной — бриф `70-workshop/specs/site-v3/
 *  05-line.md`, раздел 10, шаг 4: «Нарисовать одиннадцать путей по
 *  назначению 4.3, шаблону 4.4 и карте перекрытия 6.2. Рисуются руками,
 *  по одному, каждый — со снимком своей секции». Раздел 10, шаг 6:
 *  «Подключить реестр к странице» — `Section.astro` и `Footer.astro`
 *  читают `LINE_PATHS` напрямую, второго источника геометрии в кодовой
 *  базе больше нет (`backgroundLine.ts` считает только сторону/переход,
 *  метаданные Ч-4, не `d`).
 *
 *  До этой правки файл нёс ВТОРОЙ слой, `FALLBACK`, — механический
 *  пересчёт геометрии шага 2 для секций, ещё не нарисованных вручную.
 *  Он снят: `HAND_DRAWN` ниже покрывает все десять секций главной и
 *  подвал (раздел 10 шаг 4 завершён полностью), второй геометрии в
 *  системе не остаётся ни для одной записи. Появится одиннадцатая секция
 *  без своего пути — `LINE_PATHS[id]` будет `undefined`, и потребитель
 *  (`Section.astro`) обязан молча пропустить рисунок для неё, а не читать
 *  чужую геометрию (раздел 8: «секция без данных рисует прямую нитку в
 *  левом поле» — отдельная работа, не эта правка).
 *
 *  Помощники (`straightPath`, `traversePath`) — не общая формула вместо
 *  рисунка, а инструмент того же рода, что нёс прежний `mirrorD` в
 *  `backgroundLine.ts`: каждый вызов — решение, куда идёт путь ИМЕННО этой
 *  секции; числа (доки, амплитуда) подобраны рукой под карту перекрытия
 *  конкретной секции и проверены контракт-тестом плюс снимком на живой
 *  странице, а не выведены единой формулой на всех.
 *
 *  Третьим был `dipPath` — «выход внутрь и обратно», единственный его
 *  читатель `cases`. Правка владельца 2026-08-20 увела секцию ниже порога
 *  Г-3, событие сменилось прямой, и помощник остался бы без вызова: он снят,
 *  а не оставлен «на случай возврата». Код лежит в истории репозитория.
 *
 *  `narrow` — мобильная нитка (< 900 px, раздел 8): всегда левый док, без
 *  событий — раздел 8 «секция без данных рисует прямую нитку в левом поле»,
 *  тот же приём здесь для КАЖДОЙ секции: мобильная ширина ниже порога 900 px
 *  (раздел 6), на котором вообще стоит рисунок, событий там нет по Г-4
 *  («промежуточных значений нет»). Пока не подключена к разметке (раздел 10
 *  шаг 6 подключает только `wide`, порог видимости остаётся прежним, 480 px)
 *  — отдельная работа шага 6 плана, не эта правка.
 */
import { computeVbH, MEASURED_FOOTER_HEIGHT, MEASURED_SECTION_HEIGHT } from './backgroundLine';

/** Толщина штриха линии в единицах `viewBox` (раздел 7.2 брифа `05-line`):
 *  `stroke-width: 34` в `BackgroundLine.astro`. Единственный источник числа
 *  для контракт-теста (Г-1: `R_min ≥ 8·w`) — второй раз оно не набрано;
 *  сторож `linePaths.contract.test.ts` сверяет это значение с CSS-файлом,
 *  чтобы правка толщины в вёрстке не разошлась молча с тем, что проверяет
 *  тест. */
export const LINE_STROKE_WIDTH_VB = 34;

export interface LinePathEntry {
  /** `viewBox = 0 0 1000 vbH` — та же величина, что несёт таблица 4.1. */
  vbH: number;
  /** Путь для холста ≥ 900 px (десктопный рисунок). */
  wide: string;
  /** Путь для мобильной нитки (< 900 px, раздел 8) — прямая на доке. */
  narrow: string;
}

/* ─────────────────────── Рисование (раздел 4.3/4.4/6.2) ─────────────── */

/** Раздел 4.2: левый и правый причал, одинаковы для всех секций. */
const DOCK_LEFT = 59;
const DOCK_RIGHT = 941;
/** Раздел 3, Г-2: вынос концов пути за `viewBox` — торец `round` прячется
 *  под соседний бокс. Тот же приём, что несёт `backgroundLine.ts`. */
const OVERHANG = 60;
/** Раздел 3, Г-2: прямой вертикальный участок на каждом конце пути —
 *  порог 96, здесь взято с запасом 100, чтобы округление кривой не роняло
 *  проверку на десятые доли единицы. */
const STRAIGHT_IN_OUT = 100;

function round2(n: number): number {
  return Math.round(n * 100) / 100;
}

/** Прогон — прямая на доке `dockX` (раздел 4.3: «прямая» — секция
 *  спокойная, боковой ход 0). */
function straightPath(vbH: number, dockX: number): string {
  return `M${dockX},${-OVERHANG} L${dockX},${round2(vbH + OVERHANG)}`;
}

/** Мобильная нитка — всегда левый док, вся высота секции (раздел 8). */
function narrowPath(vbH: number): string {
  return straightPath(vbH, DOCK_LEFT);
}

/** Траверс (раздел 4.4): вертикальный вход `margin` (прямая `L`, а не
 *  затухающая кривизна кубики — раздел 12: «на этом линия ломалась уже
 *  дважды», прямой хвост гарантирует Г-2 безусловно, не приближённо), затем
 *  ОДНА симметричная кубика с вертикальной касательной на обоих концах
 *  (оба контрольных узла лежат на высоте середины хода `mid` — классическая
 *  S-кривая без стыков) — ровно та конструкция, для которой раздел 4.4
 *  считает оценку радиуса `R = 3/8 · dy² / dx`, и затем снова вертикальный
 *  выход `margin`. `xFrom` → `xTo` — доки входа и выхода (не обязательно
 *  оба края холста: у `contact` выход — середина, «сход к середине»,
 *  раздел 4.3). `margin` по умолчанию `STRAIGHT_IN_OUT` (порог Г-2 96 плюс
 *  запас); при малом `dx` (сход `contact`, 440 вместо 882) отдаётся под
 *  бо́льший `dy` кривой, чтобы Г-1 (`R ≥ 8·w`) держался тем же приёмом, не
 *  вторым числом. */
function traversePath(vbH: number, xFrom: number, xTo: number, margin = STRAIGHT_IN_OUT): string {
  const yA = margin;
  const yB = round2(vbH - margin);
  const mid = round2((yA + yB) / 2);
  return (
    `M${xFrom},${-OVERHANG} L${xFrom},${yA} ` +
    `C${xFrom},${mid} ${xTo},${mid} ${xTo},${yB} ` +
    `L${xTo},${round2(vbH + OVERHANG)}`
  );
}

const vbHOf = (id: string) => computeVbH(MEASURED_SECTION_HEIGHT[id]);

/** Одиннадцать нарисованных путей (раздел 10, шаг 4) — все десять секций
 *  главной плюс подвал, полный реестр. Ключ появился здесь по мере
 *  рисования — один за другим, каждый со своим коммитом; сейчас это
 *  единственный и полный слой (см. шапку файла). */
const HAND_DRAWN: Readonly<Record<string, LinePathEntry>> = {
  // hero — раздел 4.3: «прямая, левый причал»; первая секция страницы, с
  // неё начинается линия левым доком ([[00-overview]]).
  hero: (() => {
    const h = vbHOf('hero');
    return { vbH: h, wide: straightPath(h, DOCK_LEFT), narrow: narrowPath(h) };
  })(),
  // pain — раздел 4.3: «прямая», 663 px < 850 (Г-3) — событие не
  // помещается; продолжает левый док, на котором закончился hero.
  pain: (() => {
    const h = vbHOf('pain');
    return { vbH: h, wide: straightPath(h, DOCK_LEFT), narrow: narrowPath(h) };
  })(),
  // services — раздел 4.3: «траверс слева направо» — граница акта 1→2
  // (Ч-4). Карта 6.2: карточки 170…710/730…1270 × +245…853/+905…1426,
  // открыто сверху (< 245), в полосе +853…905 и снизу (> 1426); траверс
  // проходит между этими полосами, его вторая вершина — внутри полосы
  // карточек (раздел 4.4: «скрыта ими», для Л-2 законно).
  services: (() => {
    const h = vbHOf('services');
    return {
      vbH: h,
      wide: traversePath(h, DOCK_LEFT, DOCK_RIGHT),
      narrow: narrowPath(h),
    };
  })(),
  // pricing — раздел 4.3: «прямая, правый причал» — пауза после события
  // services, продолжает правый док, на котором тот закончился.
  pricing: (() => {
    const h = vbHOf('pricing');
    return { vbH: h, wide: straightPath(h, DOCK_RIGHT), narrow: narrowPath(h) };
  })(),
  // cases — раздел 4.3: «прямая, правый причал». До правки владельца
  // 2026-08-20 здесь стоял «выход внутрь и обратно» (`dipPath`, боковой ход
  // 300 ед., пик в зазоре между двумя полями карты 6.2) — событие для самой
  // длинной секции страницы, 2035 px.
  //
  // С правкой на главной остался один кейс, и секция стала 694 px — ниже
  // порога Г-3 (850 px, раздел 3 брифа `05-line`), на котором событие вообще
  // помещается. Решает не вкус: `dipPath` на этой высоте даёт R_min ≈ 30 при
  // требуемых 272, и сторож `linePaths.contract.test.ts` (Г-1) роняет прогон
  // — то есть кривая физически перестала быть той плавной кривой, ради
  // которой рисовалась. Тот же случай и то же лечение, что у `pain` (597 px):
  // спокойный прогон по доку, на котором закончился `pricing`. Сторона не
  // меняется (right → right), `turn` у секции по-прежнему `'none'` —
  // метаданные Ч-4 в `backgroundLine.ts` правки не требуют.
  //
  // Событие вернётся вместе с высотой: страница каталога кейсов (спека 04)
  // секцию не удлиняет, а вот второй блок на главной — да, и тогда `dipPath`
  // достают из истории, а не рисуют заново.
  cases: (() => {
    const h = vbHOf('cases');
    return { vbH: h, wide: straightPath(h, DOCK_RIGHT), narrow: narrowPath(h) };
  })(),
  // process — раздел 4.3: «траверс справа налево» — граница акта 2→3
  // (Ч-4), высота 1279 px проходит порог 850. Карта 6.2: `.panel`
  // 170…1270 × +245…1279 — закрыто почти во всю ширину и высоту секции;
  // траверс проходит под панелью (Л-2: линия ныряет под лист), видна
  // только в полях по краям.
  process: (() => {
    const h = vbHOf('process');
    return {
      vbH: h,
      wide: traversePath(h, DOCK_RIGHT, DOCK_LEFT),
      narrow: narrowPath(h),
    };
  })(),
  // guarantees — раздел 4.3: «прямая». Карта 6.2: «нет ни одной»
  // непрозрачной коробки — линия открыта целиком, поэтому она обязана
  // быть спокойной (раздел 6.2: «иначе два открытых экрана подряд
  // превратятся в единственное место, где фон кричит»).
  guarantees: (() => {
    const h = vbHOf('guarantees');
    return { vbH: h, wide: straightPath(h, DOCK_LEFT), narrow: narrowPath(h) };
  })(),
  // about — раздел 4.3: «прямая», 574 px. Карта 6.2: «нет ни одной»
  // непрозрачной коробки, как у guarantees — тот же довод: два открытых
  // экрана подряд обязаны оставаться спокойными.
  about: (() => {
    const h = vbHOf('about');
    return { vbH: h, wide: straightPath(h, DOCK_LEFT), narrow: narrowPath(h) };
  })(),
  // faq — раздел 4.3: «прямая», 543 px. Карта 6.2: `.panel` 578…1270 ×
  // +96…543 — закрыта правая половина, левая (< 578, наш причал 59)
  // открыта целиком; прямая на левом доке остаётся в открытом поле.
  faq: (() => {
    const h = vbHOf('faq');
    return { vbH: h, wide: straightPath(h, DOCK_LEFT), narrow: narrowPath(h) };
  })(),
  // contact — раздел 4.3: «сход к середине (Л-2: и дальше вниз)», боковой
  // ход 440 ед. (44 % — событие по Г-4) — выход (Ч-4), но НЕ до правого
  // причала: 966 px проходит порог 850 (раздел 3, сноска Г-3). Заканчивает
  // не на доке, а на x=499 («середина») — footer продолжает оттуда же.
  contact: (() => {
    const h = vbHOf('contact');
    const xMid = DOCK_LEFT + 440;
    return {
      vbH: h,
      wide: traversePath(h, DOCK_LEFT, xMid, 48),
      narrow: narrowPath(h),
    };
  })(),
  // footer — раздел 4.3: «прямая, за нижнюю кромку» (Л-2). Продолжает
  // contact с ТОЙ ЖЕ точки x=499 («сход к середине») — раздел 11, п. 3:
  // «на каждом стыке… горизонтальное расстояние 0 px».
  footer: (() => {
    const h = computeVbH(MEASURED_FOOTER_HEIGHT);
    const xMid = DOCK_LEFT + 440;
    return { vbH: h, wide: straightPath(h, xMid), narrow: narrowPath(h) };
  })(),
};

export const LINE_PATHS: Readonly<Record<string, LinePathEntry>> = {
  ...HAND_DRAWN,
};
