export const LINE_STROKE_WIDTH_VB = 34;

/** Один keyframe-стоп раскладки «шторки» (`.line-curtain`, `BackgroundLine.
 *  astro`) — задача «пролагивает при листании» (D-080, 2026-08-21), механика
 *  композитной замены `stroke-dashoffset`. `percent` — прогресс анимации
 *  (0…100), тот же самый прогресс `view()`-таймлайна, что раньше двигал
 *  `stroke-dashoffset` линейно по ДЛИНЕ дуги. `translate` — на сколько
 *  процентов СВОЕЙ высоты (`vbH + 2·OVERHANG`, раздел 7.1 брифа `05-line`)
 *  шторка сдвинута вниз: 0 — перекрывает путь целиком (ничего не нарисовано),
 *  100 — ушла полностью (путь открыт целиком). Поле называется и хранится
 *  по-прежнему в процентах `translate` — таблица не переписывалась вторым
 *  проходом D-080 (2026-08-21): в CSS (`BackgroundLine.astro`) это число
 *  теперь выводится не как `translate: 0 X%`, а как безразмерный
 *  `transform: scaleY(1 − X/100)` — тождественная перезапись без новых
 *  чисел, подробности у `toScaleY` в `BackgroundLine.astro`. */
export interface RevealStop {
  percent: number;
  translate: number;
}

export interface LinePathEntry {
  /** `viewBox = 0 0 1000 vbH` — та же величина, что несёт таблица 4.1. */
  vbH: number;
  /** Путь для холста ≥ 900 px (десктопный рисунок). */
  wide: string;
  /** Путь для мобильной нитки (< 900 px, раздел 8) — прямая на доке. */
  narrow: string;
  /** Keyframe-стопы шторки для `wide` (см. `RevealStop`) — уже упрощены
   *  (Дуглас–Пекер, см. `simplifyReveal`), готовы к записи в CSS
   *  `@keyframes` без второй обработки. */
  reveal: RevealStop[];
  /** `CAP_OVERHANG / vbH · 100` — на сколько процентов ВЫСОТЫ СЕКЦИИ
   *  шторка выступает за бокс сверху и снизу (`BackgroundLine.astro`,
   *  `.line-curtain`, `top`/`height`). `CAP_OVERHANG = OVERHANG + w/2`, НЕ
   *  голый `OVERHANG`: шторка обязана накрыть не только координату конца
   *  пути (`-OVERHANG … vbH+OVERHANG`), но и закрашенный `stroke-linecap:
   *  round`-полукруг вокруг неё — иначе он торчит из-под соседней шторки
   *  (дефект «оторванный кусок линии», ревью 2026-08-21, разобран у
   *  `CAP_OVERHANG` в `linePaths.ts`). */
  overhangPercent: number;
}

