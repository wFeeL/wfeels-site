/** Раздел 4.2: левый и правый причал, одинаковы для всех секций. */
const DOCK_LEFT = 59;
const DOCK_RIGHT = 941;
/** Раздел 3, Г-2: вынос концов пути за `viewBox` — торец `round` прячется
 *  под соседний бокс. Тот же приём, что несёт `backgroundLine.ts`. Это
 *  число ставит КООРДИНАТУ конца пути (`M{x},{-OVERHANG}` и симметрично на
 *  выходе), не более — Г-2 читает его как «путь стоит не ближе 60 единиц
 *  к своему видимому боксу», и контракт-тест меряет ровно эту координату. */
const OVERHANG = 60;
/** Дефект «оторванный кусок линии» (ревью 2026-08-21, разбор задачи «шторка
 *  соседних секций едет не синхронно»): у КООРДИНАТЫ конца пути (`OVERHANG`
 *  выше) есть покрашенный `stroke-linecap: round`, и его КРУГ выходит за эту
 *  координату ещё на `stroke-width / 2` — половину толщины штриха, в
 *  направлении ОТ видимого бокса. Шторка (её `top`/`height`, раздел 7.1
 *  брифа `05-line`) до правки использовала тот же `OVERHANG`, что и
 *  координата пути, — то есть накрывала домен `[-OVERHANG, vbH+OVERHANG]`,
 *  а реально закрашенная часть штриха доходит до `[-OVERHANG-w/2,
 *  vbH+OVERHANG+w/2]`. Полоса шириной `w/2` (17 единиц `viewBox` при
 *  `w = 34` — на экране те самые «~18 px высотой», что измерило ревью)
 *  оставалась некрытой СВОЕЙ шторкой; она не была видна там, где путь один
 *  на секцию (нечему было её обнажить), но все `.line`/`.line-curtain`
 *  делят ОДИН стековый контекст на `z-index: -1` (раздел 6.1 брифа) и
 *  красятся в порядке DOM — путь СЛЕДУЮЩЕЙ секции (позже в DOM) кроет своим
 *  некрытым полукругом шторку ПРЕДЫДУЩЕЙ, даже когда та ещё не домоталась
 *  до конца. Отсюда «оторванный кусок»: чужой некрытый полукруг поверх
 *  чужой же ещё закрытой шторки.
 *
 *  Лечение — шторка (её бокс И таблица `reveal`, откуда берётся `scaleY`)
 *  обязана мерить СВОЙ домен от `CAP_OVERHANG`, не от `OVERHANG`: она
 *  прячет не только координату конца пути, но и весь закрашенный круг
 *  вокруг неё. Координата `d` (сам путь, `OVERHANG`) не трогается — это
 *  число отвечает только за Г-2 и вертикальный стык, к покраске штриха
 *  отношения не имеет. */
const CAP_OVERHANG = OVERHANG + LINE_STROKE_WIDTH_VB / 2;
/** Раздел 3, Г-2: прямой вертикальный участок на каждом конце пути —
 *  порог 96, здесь взято с запасом 100, чтобы округление кривой не роняло
 *  проверку на десятые доли единицы. */
const STRAIGHT_IN_OUT = 100;

function round2(n: number): number {
  return Math.round(n * 100) / 100;
}

/* ─────────────────── Шторка (задача «пролагивает», D-080) ─────────────────
 *
 * `stroke-dashoffset` не композитится Chromium — каждый кадр перерисовывает
 * и растрирует весь бокс `.line` заново (замер владельца, `DECISIONS.md`
 * D-080). Композируемая замена: путь нарисован ЦЕЛИКОМ и статически, а
 * открывается шторкой (`.line-curtain`, непрозрачный див того же цвета, что
 * фон за линией — раздел 6.1 брифа `05-line`: линия красится строго между
 * фоном `body`/`footer` и всеми в потоке идущими поверхностями, значит цвет
 * ЗА линией везде один и тот же плоский `--bg`/микс подвала, вторая правда
 * фона не нужна), которую двигает `transform: scaleY(1 − X/100)` (`X` — та
 * же величина, что несёт `translate` ниже) на ТОМ ЖЕ `view()`-таймлайне —
 * ПРАВКА 2026-08-21, второй проход того же дня: первая версия двигала
 * `translate: 0 X%`, но `%` здесь считается от высоты ЭЛЕМЕНТА, а не
 * безразмерно, и такую величину компоузер разрешить сам не может — замер в
 * настоящем браузере (`headed.mjs`) держал 38 пропущенных кадров вместо
 * цели ≤10. `scaleY` — безразмерный множитель, компоузер считает его сам,
 * без обращения к главному потоку; тождество точное, новых чисел нет
 * (`BackgroundLine.astro`, `toScaleY`).
 *
 * Раньше `stroke-dashoffset` открывал путь ЛИНЕЙНО ПО ДЛИНЕ ДУГИ (`pathLength
 * = 1`, `dasharray: 1 1`) — для прямых прогонов это то же самое, что линейно
 * по Y, а для траверсов (S-кривая) — НЕТ: дуга тратит часть длины на
 * горизонтальный ход, и точка, до которой дошла дуга при прогрессе `p`,
 * стоит по Y НИЖЕ, чем `p · vbH`. Чтобы картинка на КАЖДОМ шаге прокрутки
 * осталась той же самой (жёсткое условие D-080), а не только по краям
 * диапазона, шторка не просто едет линейно 0→100% — её путь по Y считается
 * ЧИСЛЕННО по ТОЙ ЖЕ геометрии, что несёт сам путь: `resampleByLength`
 * (`lib/pathGeometry.ts`, тот же инструмент, что и контракт-тест раздела 10
 * шаг 3) даёт точки, равномерные по ДЛИНЕ ДУГИ — i-я точка при `N` точках
 * это ровно то положение, в которое старый `stroke-dashoffset` привёл бы
 * кончик при прогрессе `i/(N-1)`. Для прямых путей (семь из одиннадцати)
 * таблица выходит линейной автоматически — точки на прямой равномерны по Y
 * и по длине дуги одновременно, второй ветки «прямая/кривая» здесь не
 * заводится: один и тот же код проходит через оба случая. */

/** Количество точек ПЕРЕД упрощением — с запасом на кривизну траверсов
 *  (S-дуга, раздел 4.4): реже — рискуем смазать пик кривизны, чаще —
 *  не изменит результат после `simplifyReveal`, только время сборки. */
const REVEAL_SAMPLE_COUNT = 41;
/** Допуск упрощения Дугласа–Пекера, в тех же единицах, что и оси таблицы
 *  (проценты по обеим осям) — 0,15 % высоты секции на секции ~1000…2000 px
 *  это 1,5…3 px, значительно меньше толщины штриха (31…48 px, раздел 5.1):
 *  зрительно неотличимо от точной кривой, а для семи прямых путей сводит
 *  таблицу ровно к двум точкам (0 % и 100 %) — CSS не растёт лишним весом
 *  там, где кривизны нет вовсе. */
const REVEAL_SIMPLIFY_TOLERANCE = 0.15;

/** Расстояние точки `p` до отрезка `a→b` в той же двумерной системе
 *  (percent, translate) — обычная проекция на отрезок с зажимом `t∈[0,1]`. */
function pointToSegmentDistance(p: RevealStop, a: RevealStop, b: RevealStop): number {
  const dx = b.percent - a.percent;
  const dy = b.translate - a.translate;
  const len2 = dx * dx + dy * dy;
  if (len2 === 0) return Math.hypot(p.percent - a.percent, p.translate - a.translate);
  const t = Math.max(0, Math.min(1, ((p.percent - a.percent) * dx + (p.translate - a.translate) * dy) / len2));
  const px = a.percent + t * dx;
  const py = a.translate + t * dy;
  return Math.hypot(p.percent - px, p.translate - py);
}

/** Дуглас–Пекер по двум осям (percent, translate) — держит только те стопы,
 *  без которых кривая отклонилась бы больше допуска. Прямая линия (семь
 *  путей из одиннадцати) сводится к двум точкам; траверс — к горстке точек
 *  вокруг S-дуги. Меньше CSS, тот же зрительный результат (раздел 13 брифа
 *  `05-line`: вес — не вкус). */
function simplifyReveal(points: readonly RevealStop[], tolerance: number): RevealStop[] {
  if (points.length <= 2) return [...points];
  let maxDist = 0;
  let splitAt = 0;
  const first = points[0];
  const last = points[points.length - 1];
  for (let i = 1; i < points.length - 1; i++) {
    const d = pointToSegmentDistance(points[i], first, last);
    if (d > maxDist) {
      maxDist = d;
      splitAt = i;
    }
  }
  if (maxDist > tolerance) {
    const left = simplifyReveal(points.slice(0, splitAt + 1), tolerance);
    const right = simplifyReveal(points.slice(splitAt), tolerance);
    return [...left.slice(0, -1), ...right];
  }
  return [first, last];
}

/** Строит таблицу шторки для одного пути — раздел выше. Домен ЭТОЙ таблицы
 *  (`span`, `translate`) остаётся на `OVERHANG` — намеренно НЕ на
 *  `CAP_OVERHANG`. Таблица кодирует ДВИЖЕНИЕ кончика по ДЛИНЕ ДУГИ пути (то,
 *  что раньше двигал `stroke-dashoffset` линейно), а путь по-прежнему стоит
 *  на координатах `∓OVERHANG` (раздел выше) — трогать этот домен значило бы
 *  либо ломать «восемь прямых путей → два стопа» (натуральная формула по
 *  `CAP_OVERHANG` перестаёт быть коллинеарной с (0,0)–(100,100), проверено
 *  и отброшено — рабочая копия правки в истории коммитов задачи «пролагивает
 *  при листании»), либо подгонять её обратно вручную вторым числом.
 *
 *  Домен ШТОРКИ (`overhangPercent`, `buildEntry` ниже) — другое дело и
 *  меняется на `CAP_OVERHANG`: сама таблица `translate` домен-агностична —
 *  `0` и `100` дают `scaleY(1)`/`scaleY(0)` при ЛЮБОМ размере бокса (крайние
 *  значения шкалы, не зависящие от того, что стоит в знаменателе), а именно
 *  эти два значения и есть состояние ДО начала окна раскрытия и ПОСЛЕ его
 *  конца (`animation-fill-mode: both`) — то самое состояние, в котором
 *  сегодня стоит соседняя секция, пока не началось ЕЁ собственное окно
 *  (дефект «оторванный кусок линии», ревью 2026-08-21: шторка соседа была
 *  ровно в `scaleY(1)`, но бокс, который она накрывала, был мал на `w/2`).
 *  Расширение бокса (без изменения таблицы) чинит ровно этот, замеренный
 *  случай — оба конца окна раскрытия остаются точными `scaleY(1)`/`scaleY(0)`
 *  над бо́льшим боксом. Внутри самого окна (0 < percent < 100) это даёт
 *  сглаженную и небольшую (≈ `w/2` единиц `viewBox`, доли процента высоты
 *  секции — раздел 5 брифа `05-line`, `w` — 31…48 px, `w/2` — 15…24 px)
 *  задержку кончика у САМОЙ границы видимого бокса; проверено сторожем
 *  `background-line-ink-continuity.spec.ts` — задержка не даёт нового
 *  разрыва ни на одной из проверенных ширин и тем. */
function revealKeyframes(d: string, vbH: number): RevealStop[] {
  const dense = resampleByLength(flattenPath(d), REVEAL_SAMPLE_COUNT);
  const span = vbH + 2 * OVERHANG;
  const raw = dense.map((p, i) => ({
    percent: round2((i / (REVEAL_SAMPLE_COUNT - 1)) * 100),
    translate: round2(((p.y + OVERHANG) / span) * 100),
  }));
  return simplifyReveal(raw, REVEAL_SIMPLIFY_TOLERANCE);
}

/** Единственная точка сборки записи реестра — раньше каждая запись
 *  собирала объектный литерал руками, теперь ещё считает шторку и её вынос
 *  в процентах (раздел выше), не по второму разу на каждый вызов.
 *  `overhangPercent` — от `CAP_OVERHANG` (см. его комментарий), не от
 *  `OVERHANG`: шторка обязана закрыть весь закрашенный полукруг конца
 *  штриха, а не только координату, в которой путь формально кончается. */
function buildEntry(vbH: number, wide: string, narrow: string): LinePathEntry {
  return {
    vbH,
    wide,
    narrow,
    reveal: revealKeyframes(wide, vbH),
    overhangPercent: round2((CAP_OVERHANG / vbH) * 100),
  };
}

/** Прогон — прямая на доке `dockX` (раздел 4.3: «прямая» — секция
 *  спокойная, боковой ход 0). */
function straightPath(vbH: number, dockX: number): string {
  return `M${dockX},${-OVERHANG} L${dockX},${round2(vbH + OVERHANG)}`;
}

/** Мобильная нитка — всегда левый док, вся высота секции (раздел 8). */
function narrowPath(vbH: number): string {
  return straightPath(vbH, DOCK_LEFT);
}

/** Траверс (раздел 4.4): вертикальный вход `margin` (прямая `L`, а не
 *  затухающая кривизна кубики — раздел 12: «на этом линия ломалась уже
 *  дважды», прямой хвост гарантирует Г-2 безусловно, не приближённо), затем
 *  ОДНА симметричная кубика с вертикальной касательной на обоих концах
 *  (оба контрольных узла лежат на высоте середины хода `mid` — классическая
 *  S-кривая без стыков) — ровно та конструкция, для которой раздел 4.4
 *  считает оценку радиуса `R = 3/8 · dy² / dx`, и затем снова вертикальный
 *  выход `margin`. `xFrom` → `xTo` — доки входа и выхода (не обязательно
 *  оба края холста: у `contact` выход — середина, «сход к середине»,
 *  раздел 4.3). `margin` по умолчанию `STRAIGHT_IN_OUT` (порог Г-2 96 плюс
 *  запас); при малом `dx` (сход `contact`, 440 вместо 882) отдаётся под
 *  бо́льший `dy` кривой, чтобы Г-1 (`R ≥ 8·w`) держался тем же приёмом, не
 *  вторым числом. */
function traversePath(vbH: number, xFrom: number, xTo: number, margin = STRAIGHT_IN_OUT): string {
  const yA = margin;
  const yB = round2(vbH - margin);
  const mid = round2((yA + yB) / 2);
  return (
    `M${xFrom},${-OVERHANG} L${xFrom},${yA} ` +
    `C${xFrom},${mid} ${xTo},${mid} ${xTo},${yB} ` +
    `L${xTo},${round2(vbH + OVERHANG)}`
  );
}

