/** Пути, которые не попадают в sitemap: служебные и юридические черновики.
 *
 *  С 2026-08-26 у трёх правовых страниц и у «спасибо» есть английские
 *  двойники под `/en/…` (перевод с оговоркой о приоритете русской редакции,
 *  а не второй документ) — совпадение проверяется точным путём или
 *  каталогом (см. `isIndexable` ниже), поэтому `/en/privacy` НЕ подпадает
 *  под запись `/privacy` автоматически и нуждается в собственной строке.
 *
 *  `/404` (русская) в этом списке нет и не нужна: её без нашего участия
 *  снимает сам `@astrojs/sitemap` (`STATUS_CODE_PAGES`, `isStatusCodePage`
 *  в его исходнике) — но только для путей БЕЗ языкового префикса, потому
 *  что интеграция вызвана в `astro.config.mjs` без опции `i18n.locales`
 *  (у нас свой список локалей уже есть в `i18n/locales.ts`, заводить второй
 *  ради библиотеки не стали). Поэтому `/en/404` тем же встроенным
 *  механизмом НЕ снимается и нуждается в собственной строке здесь, как и
 *  правовые страницы выше. */
export const SITEMAP_EXCLUDED = [
  '/dev',
  '/privacy',
  '/en/privacy',
  '/terms',
  '/en/terms',
  '/consent',
  '/en/consent',
  '/thanks',
  '/en/thanks',
  '/en/404',
];

/**
 * Совпадение точное или по каталогу. Проверять простым `startsWith` нельзя:
 * тогда будущая `/privacy-archive` молча выпала бы из карты сайта заодно
 * с настоящей `/privacy`.
 */
export function isIndexable(pathname: string): boolean {
  return !SITEMAP_EXCLUDED.some(
    (p) => pathname === p || pathname.startsWith(`${p}/`)
  );
}
