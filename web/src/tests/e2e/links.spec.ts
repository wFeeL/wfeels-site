import { test, expect } from '@playwright/test';

/** Ссылки сайта, за которыми страницы ЕЩЁ НЕТ.
 *
 *  Это не поблажка тесту, а запись факта: сегодня посетитель, дошедший до
 *  одной из этих ссылок, получает 404. Пункты меню (`lib/nav.ts`) сегодня —
 *  якоря на секции главной и в обход не попадают вовсе (крауler игнорирует
 *  чистые якоря, см. фильтр ниже); сюда попадают ссылки секции 3 главной
 *  («Что я делаю», `data/services.ts`) на каталог услуг, девять посадочных
 *  услуг и четыре нишевые страницы — их приносит спека 03 «Посадочные»
 *  (`70-workshop/specs/site-v3/00-overview.md`, раздел 8).
 *
 *  Ожидание записано как `toBe(404)`, а не как пропуск, и это главное. Пропуск
 *  молчал бы вечно: страницу построят, список останется, и следующий, кто
 *  сломает `/services`, увидит зелёный. Точное ожидание истекает само — в день,
 *  когда страница появится, тест станет красным и потребует убрать строку
 *  отсюда. Ни одна ссылка не выпадает из-под наблюдения: список закрытый, и
 *  любой НОВЫЙ битый адрес по-прежнему валит прогон. */
const NOT_BUILT_YET = [
  // Оставлены с задачи фундамента про запас: если где-то на сайте появится
  // прямая ссылка на страницу по этому адресу (а не на якорь главной,
  // `/#services` и подобные — их шапка использует сегодня, `lib/nav.ts`),
  // обход не должен упасть неожиданно. Страниц по этим адресам план
  // фундамента не строит.
  '/services', '/cases', '/pricing', '/about',

  // Спека 03 «Посадочные»: тонкий каталог и девять страниц услуг. Ссылки на
  // них приносит секция 3 главной («Что я делаю», план `02-home-plan.md`,
  // задача 7) — карточки указывают на эти адреса уже сегодня, хотя страниц
  // под ними ещё нет. Адреса предварительные (`data/services.ts`, шапка
  // файла): спека 03 вправе их переименовать.
  '/services/website',
  '/services/website-support',
  '/services/website-audit',
  '/services/integrations',
  '/services/admin-panel',
  '/services/backend-api',
  '/services/ai-consultant',
  '/services/telegram-bot',
  '/services/telegram-miniapp',

  // Спека 03 «Посадочные»: четыре нишевые страницы, ответвления S1. Ссылки на
  // них приносит строка ниш секции 3 главной (`data/services.ts`, `NICHES`).
  '/niches/pet-care',
  '/niches/beauty-salons',
  '/niches/craftsmen',
  '/niches/clinics',

  // Спека 04 «Кейсы»: шаблон страницы кейса. Ссылки на три страницы приносит
  // секция 5 главной («Кейсы», план `02-home-plan.md`, задача 9) — карточки
  // указывают на эти адреса уже сегодня, страниц под ними ещё нет.
  '/cases/site-v3',
  '/cases/zayavka-hub',
  '/cases/ai-consultant',
  // Тизер фабрики той же секции 5 ведёт на страницу кейса фабрики — тоже
  // спека 04 (`data/cases.ts`, `FACTORY_TEASER.href`).
  '/cases/bot-factory',
];

/** Внутренние ссылки: обход, а не список.
 *
 *  Проверено мутацией: адрес согласия под формой (`LeadForm.astro`) можно было
 *  заменить на несуществующий, и весь набор оставался зелёным — 50 passed.
 *  Ссылка была цела по совпадению двух независимых строк, а не потому, что за
 *  ней кто-то следил. То же касалось юридических ссылок подвала: их проверяли
 *  на видимость, а не на переход.
 *
 *  Почему обход, а не сверка `href` со списком маршрутов: список маршрутов —
 *  третья ручная копия тех же путей, и он молчит про ссылку, которую завтра
 *  добавят на новой странице. Обход же спрашивает у сервера то же, что спросит
 *  браузер посетителя, и сам расширяется вместе с сайтом. */
test('каждая внутренняя ссылка ведёт на существующую страницу', async ({ page }) => {
  const queue = ['/'];
  const seen = new Set(queue);
  const visited: string[] = [];
  // Откуда пришла ссылка — иначе отчёт назовёт битый адрес, но не место правки.
  const from = new Map<string, string>([['/', 'начало обхода']]);

  while (queue.length) {
    const path = queue.shift()!;
    const res = await page.goto(path);
    const expected = NOT_BUILT_YET.includes(path) ? 404 : 200;
    expect(res?.status(), `${path} — ссылка со страницы ${from.get(path)}`)
      .toBe(expected);
    visited.push(path);

    const hrefs = await page.locator('a[href]')
      .evaluateAll((links) => links.map((l) => l.getAttribute('href') ?? ''));

    for (const href of hrefs) {
      // Внешние адреса и чистые якоря не наша зона: за t.me отвечает Telegram,
      // а `#main` никуда не уходит со страницы.
      if (!href.startsWith('/')) continue;
      const clean = href.split('#')[0].split('?')[0].replace(/(.)\/$/, '$1');
      if (!clean || seen.has(clean)) continue;
      seen.add(clean);
      from.set(clean, path);
      queue.push(clean);
    }
  }

  // Обход, который никуда не дошёл, зелёный и бесполезен. Перечислены страницы,
  // до которых он ОБЯЗАН добраться: контакт — с формой, три юридические — из
  // подвала и из подписи под чекбоксом.
  expect(visited).toEqual(expect.arrayContaining(
    ['/contact', '/privacy', '/terms', '/consent', '/en'],
  ));
});

/** Ответ 200 говорит, что страница есть, но не что она та самая. Согласие —
 *  единственная ссылка на сайте, где подмена адреса на другой существующий
 *  документ была бы прямой неправдой: человек ставит галочку под конкретным
 *  текстом. Поэтому здесь проверяется не код ответа, а куда пришли. */
test('ссылка под чекбоксом формы открывает согласие на обработку данных',
  async ({ page }) => {
    await page.goto('/contact');
    await page.locator('form .consent a').click();

    await expect(page).toHaveURL(/\/consent$/);
    await expect(page.locator('h1'))
      .toHaveText('Согласие на обработку персональных данных');
  });
