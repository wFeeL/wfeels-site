import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

/* Правка владельца 2026-08-18, пункт 1 списка правок
 * (`70-workshop/specs/site-v3/03-redesign-2026-08-14.md`): собранный
 * `dist/index.html` разбит на читаемые блоки по секциям. Причина была в
 * сжатии разметки, которое Astro делает по умолчанию, — до правки главная
 * выходила в 39 строках, самая длинная 75 273 символа.
 *
 * Сторож нужен потому, что вернуть сжатие можно одной строкой в
 * `astro.config.mjs` (`compressHTML`), и сделать это можно случайно — при
 * обновлении Astro, при копировании конфига, при попытке «немного сэкономить
 * вес». Молча это не пройдёт.
 *
 * Цена читаемости измерена и невелика: 7,9 КБ сырых байтов и 0,9 КБ по сети
 * (20,0 → 20,9 КБ в gzip). Отступы и переводы строк — самые сжимаемые байты,
 * какие бывают. Гейт веса (`scripts/check-budget.mjs`) считает сырые байты,
 * поэтому число на самой странице пересчитано вместе с этой правкой. */
describe('dist/index.html — разметка читаема человеком', () => {
  const html = readFileSync(
    resolve(process.cwd(), 'dist/index.html'),
    'utf8',
  );
  const lines = html.split('\n');
  const longest = lines.reduce((m, l) => Math.max(m, l.length), 0);

  it('файл не склеен в несколько длинных строк', () => {
    expect(
      lines.length,
      `строк всего ${lines.length} — похоже, сжатие разметки включили обратно`,
    ).toBeGreaterThan(300);
  });

  it('ни одна строка не длиннее экрана в разы', () => {
    // 8000 — с большим запасом: сегодня самая длинная 3 713, и это
    // встроенный стиль, а не разметка. Порог ловит возврат сжатия
    // (75 273 символа), а не колебания вёрстки.
    expect(
      longest,
      `самая длинная строка ${longest} символов`,
    ).toBeLessThan(8000);
  });

  it('каждую секцию можно найти по своей строке', () => {
    /* Смысл правки владельца: найти секцию в файле глазами. Проверяется
       именно это, а не форматирование вообще.

       Требовать, чтобы строка НАЧИНАЛАСЬ с `<section`, было бы строже, чем
       нужно: сборщик оставляет закрывающий тег предыдущей секции на той же
       строке (`</section><section id="services"`), и это не мешает ни
       поиску, ни чтению. Важно, что у каждой секции своя строка, а не то,
       что перед ней ничего нет. */
    const sectionLineNumbers = lines
      .map((l, i) => (l.includes('<section') ? i : -1))
      .filter((i) => i >= 0);
    const sectionCount = (html.match(/<section[\s>]/g) ?? []).length;

    expect(sectionCount, 'секций в разметке не найдено').toBeGreaterThan(5);
    expect(
      sectionLineNumbers.length,
      `секций ${sectionCount}, а строк с ними ${sectionLineNumbers.length} — ` +
      'значит несколько секций слиплись в одну строку',
    ).toBe(sectionCount);
  });
});
