import { describe, it, expect } from 'vitest';
import { existsSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

/* Сторож ссылок в никуда на главной.
 *
 * Заведён 2026-08-20 по следу конкретного дефекта. Под секцией кейсов стояла
 * кнопка «Все кейсы» на `/cases` — страницы по этому адресу нет и не было, то
 * есть кнопка вела в 404. Дефект жил незамеченным при полностью зелёном
 * прогоне, потому что сторож проверял НАЛИЧИЕ АДРЕСА В РАЗМЕТКЕ
 * (`expect(html).toContain(CASES_CATALOG_HREF)`), а не наличие страницы по
 * этому адресу. Тот же класс ошибки — «проверка есть, проверяет не то» — в
 * этом репозитории ловили уже трижды.
 *
 * Проверяется СБОРКА, а не список маршрутов: у каждого внутреннего `href`
 * главной обязан существовать файл в `dist/`. Список маршрутов был бы третьей
 * ручной копией тех же путей и молчал бы ровно там, где молчал прежний тест.
 *
 * Почему это не дубль обхода `e2e/links.spec.ts`. Обход спрашивает у сервера
 * то же, что спросит браузер, — и это сильнее. Но у него есть список
 * `NOT_BUILT_YET` с записями «оставлены про запас», и `/cases` лежал в нём
 * ЗАДОЛГО до появления кнопки: в день, когда кнопку добавили, обход застал
 * готовое разрешение и промолчал. Здесь этой лазейки нет — см. правило
 * «список без запаса» ниже. Плюс этот сторож не требует браузера и падает уже
 * на `npm run test:unit`.
 */

const DIST = fileURLToPath(new URL('../../dist/', import.meta.url));
const DIST_INDEX = `${DIST}index.html`;

/** Адреса, которых в сборке заведомо нет, — вместе с причиной.
 *
 *  Правило списка ОДНО и оно жёсткое: **никакого запаса**. Адрес попадает
 *  сюда только тогда, когда ссылка на него уже стоит на главной, и уходит
 *  отсюда в тот же день, когда ссылка снята или страница построена. Тест
 *  проверяет это в обе стороны: неизвестный битый адрес роняет прогон, и
 *  лишняя запись — тоже. Именно запись «про запас» и спрятала кнопку «Все
 *  кейсы»; без запаса добавить ссылку в никуда молча нельзя — придётся
 *  сознательно вписать её сюда, и это увидят при разборе правки.
 */
const KNOWN_UNBUILT: ReadonlyArray<{ path: string; why: string }> = [
  /* Спека 03 «Посадочные»: тонкий каталог услуг и девять страниц услуг.
     Ссылки приносит секция 3 главной (`data/services.ts`). */
  {
    path: '/services',
    /* ЭТО ТОТ ЖЕ ДЕФЕКТ, что и снятая кнопка «Все кейсы»: под секцией услуг
       стоит кнопка «Все услуги» на несуществующую страницу. Правка владельца
       2026-08-20 касалась только кейсов, решения по услугам нет — поэтому
       кнопка на месте, а факт записан здесь открытым текстом, а не спрятан
       в общем списке ожидаемых 404. */
    why: 'кнопка «Все услуги» под секцией 3; страницу строит спека 03',
  },
  { path: '/services/website', why: 'карточка услуги, спека 03' },
  { path: '/services/website-support', why: 'карточка услуги, спека 03' },
  { path: '/services/website-audit', why: 'карточка услуги, спека 03' },
  { path: '/services/integrations', why: 'карточка услуги, спека 03' },
  { path: '/services/admin-panel', why: 'карточка услуги, спека 03' },
  { path: '/services/backend-api', why: 'карточка услуги, спека 03' },
  { path: '/services/ai-consultant', why: 'карточка услуги, спека 03' },
  { path: '/services/telegram-bot', why: 'карточка услуги, спека 03' },
  { path: '/services/telegram-miniapp', why: 'карточка услуги, спека 03' },

  /* Спека 03: четыре нишевые страницы, строка ниш секции 3. */
  { path: '/niches/pet-care', why: 'строка ниш секции 3, спека 03' },
  { path: '/niches/beauty-salons', why: 'строка ниш секции 3, спека 03' },
  { path: '/niches/craftsmen', why: 'строка ниш секции 3, спека 03' },
  { path: '/niches/clinics', why: 'строка ниш секции 3, спека 03' },

  /* Записи `/cases/site-v3` здесь БОЛЬШЕ НЕТ. Правка владельца 2026-08-20
     сняла ссылку с заголовка блока секции 5 («пока убираем ссылку с кейса
     „Этот сайт“, иначе она ведет на несуществующую страницу»), и запись
     ушла в тот же день — ровно по правилу «никакого запаса» выше. Оставить
     её значило бы завести тот самый задел на будущее, который однажды уже
     спрятал кнопку «Все кейсы»: адрес был бы заранее разрешён, и следующая
     ссылка на несуществующую страницу кейса прошла бы молча. */
];

describe('dist/index.html — ни одной ссылки в никуда', () => {
  it('сборка существует (npm run build перед этим набором)', () => {
    if (!existsSync(DIST_INDEX)) {
      throw new Error(
        `\n${DIST_INDEX} не найден. Сначала выполни \`npm run build\` в web/, ` +
        'затем повтори `npm run test:unit`.',
      );
    }
    expect(true).toBe(true);
  });

  if (!existsSync(DIST_INDEX)) return;
  const html = readFileSync(DIST_INDEX, 'utf8');

  /** Внутренние адреса главной: без внешних, без чистых якорей, без
   *  query-хвоста, без завершающего слеша (кроме корня). */
  const internal = [...new Set(
    [...html.matchAll(/href="([^"]+)"/g)]
      .map((m) => m[1])
      .filter((h) => h.startsWith('/'))
      .map((h) => h.split('#')[0].split('?')[0].replace(/(.)\/$/, '$1'))
      .filter((h) => h.length > 0),
  )].sort();

  /** Есть ли в сборке файл, который отдаст этот адрес. Проверяются все три
   *  формы, в которых Astro кладёт вывод: каталог со своим `index.html`,
   *  одиночный `.html` и обычный файл (шрифт, стиль, иконка). */
  function builtIn(path: string): boolean {
    const rel = path.replace(/^\//, '');
    if (rel === '') return existsSync(`${DIST}index.html`);
    return existsSync(`${DIST}${rel}/index.html`)
      || existsSync(`${DIST}${rel}.html`)
      || existsSync(`${DIST}${rel}`);
  }

  it('обход нашёл ссылки — пустой список зелен и бесполезен', () => {
    expect(internal.length).toBeGreaterThan(10);
    expect(internal, 'сама главная').toContain('/');
  });

  const unbuilt = new Map(KNOWN_UNBUILT.map((e) => [e.path, e.why]));

  for (const path of internal) {
    it(`${path} — страница есть в сборке`, () => {
      if (unbuilt.has(path)) {
        expect(
          builtIn(path),
          `${path} УЖЕ построен — убери запись из KNOWN_UNBUILT: ` +
          `«${unbuilt.get(path)}»`,
        ).toBe(false);
        return;
      }
      expect(
        builtIn(path),
        `ссылка в никуда: главная ведёт на ${path}, а в dist/ нет ни ` +
        `${path}/index.html, ни ${path}.html, ни файла по этому пути. ` +
        'Либо снимите ссылку, либо постройте страницу, либо — если страница ' +
        'запланирована и решение принято — впишите адрес в KNOWN_UNBUILT ' +
        'вместе с причиной.',
      ).toBe(true);
    });
  }

  it('в KNOWN_UNBUILT нет записей «про запас»: каждая описывает живую ссылку', () => {
    // Ровно эта проверка и сломала бы прежний дефект на подходе. Запись
    // `/cases`, лежавшая в списке ожидаемых 404 задолго до появления кнопки,
    // здесь не пережила бы и одного прогона.
    for (const { path, why } of KNOWN_UNBUILT) {
      expect(
        internal,
        `KNOWN_UNBUILT несёт ${path} («${why}»), но ссылки на этот адрес на ` +
        'главной нет. Список — запись о сегодняшнем состоянии, а не задел на ' +
        'будущее: убери строку.',
      ).toContain(path);
    }
  });
});
