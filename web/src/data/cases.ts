// Меток происхождения нет нигде (общая спека, раздел 7), и слова «клиент»,
// «заказчик», «для компании» в описаниях запрещены — все три кейса на
// главной собственные продукты, а не работа по оплаченному заказу
// (40-portfolio/CLAUDE.md).

export interface CaseCard {
  /** Адрес страницы кейса — `/cases/<slug>`. Страниц пока нет (спека 04):
   *  адрес объявлен ожидаемой 404 в `tests/e2e/links.spec.ts`. */
  slug: string;
  /** Заголовок карточки — дословно из 02-texts.md. */
  title: string;
  /** Описание — дословно из 02-texts.md. Только у кейсов на главной: текст
   *  трёх остальных кейсов не утверждён владельцем построчно и не пишется
   *  по рыбе (план 02-home-plan.md, задача 1). */
  description?: string;
  /** Строка стека, моноширинная, латиницей — дословно из 02-texts.md. */
  stack?: string;
  /** Карточка показывается на главной. */
  onHome: boolean;
  /** Порядок карточки на главной — зеркалит порядок строк первого экрана
   *  (Сайты и лендинги → Автоматизация и интеграции → ИИ-консультант).
   *  Отсутствует у кейсов вне главной. */
  homeOrder?: number;
}

