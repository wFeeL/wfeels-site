// (`components/home/Cases.astro`, `components/home/CaseRow.astro`) читает
// отсюда, а не хранит текст сама.
//
// Текст — дословно из `70-workshop/specs/site-v3/02-texts.md`, секция 5. Ни
// слова не менять при правке: формулировки утверждены владельцем, решения
// объяснены в блоке «Что здесь нельзя менять при правке» того же документа.
//
// Пять кейсов существуют, но главная показывает только три:
//
//   Сайты и лендинги            → этот сайт
//   ИИ-консультант               → ИИ-консультант
//   Автоматизация и интеграции  → Заявка-Хаб
//
// Четвёртым блоком до 2026-08-19 стояла «Фабрика ботов» (D-048,
// `04-cases-brief.md`, раздел 6.4). Владелец снял её с главной правкой
// 2026-08-19 — вместе с ней ушли её данные (`data/factory.ts`), рисунок
// «Стеллаж» (`CaseFactoryIllustration.astro`) и их сторожа. Код остаётся в
// истории репозитория: если кейс вернут, его достают оттуда, а не пишут
// заново. Правило чередования сторон (`homeOrder % 2 === 0`) от снятия не
// меняется — три блока идут как обычный, зеркальный, обычный.
//
// Остальные два (SlotBook, Storefront) уходят на /cases — спека 04, которой
// ещё нет. Их карточная копия для страницы кейсов там же не утверждена
// владельцем построчно, поэтому здесь у них есть только заголовок и адрес:
// описание — задача спеки 04, не этого плана.
//
// Меток происхождения нет нигде (общая спека, раздел 7), и слова «клиент»,
// «заказчик», «для компании» в описаниях запрещены — все три кейса на
// главной собственные продукты, а не работа по оплаченному заказу
// (40-portfolio/CLAUDE.md).

export interface CaseCard {
  /** Адрес страницы кейса — `/cases/<slug>`. Страниц пока нет (спека 04):
   *  адрес объявлен ожидаемой 404 в `tests/e2e/links.spec.ts`. */
  slug: string;
  /** Заголовок карточки — дословно из 02-texts.md. */
  title: string;
  /** Описание — дословно из 02-texts.md. Только у кейсов на главной: текст
   *  двух остальных кейсов не утверждён владельцем построчно и не пишется
   *  по рыбе (план 02-home-plan.md, задача 1). */
  description?: string;
  /** Строка стека, моноширинная, латиницей — дословно из 02-texts.md. */
  stack?: string;
  /** Карточка показывается на главной. */
  onHome: boolean;
  /** Порядок карточки на главной — D-048 (`04-cases-brief.md`, раздел 2.1),
   *  без снятой 2026-08-19 «Фабрики ботов»: этот сайт → ИИ-консультант →
   *  Заявка-Хаб. Стороны чередуются формулой `homeOrder % 2 === 0`
   *  (`CaseRow.astro`). Отсутствует у кейсов вне главной. */
  homeOrder?: number;
}

