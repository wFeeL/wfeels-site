import { describe, it, expect } from 'vitest';
import { FACTORY_TEASER } from './cases';
import { FACTORY_TOTALS } from './factory';

/** Абзац тизера фабрики называет числа СЛОВАМИ: «Четыре типа, тридцать две
 *  темы». Плита рядом берёт те же величины из `FACTORY_TOTALS`, то есть из
 *  данных.
 *
 *  Связи между ними нет и быть не может: одно — утверждённый владельцем текст
 *  (бриф `02-home-core.md`, раздел 12), другое — числа. Вырастет число тем —
 *  плита пересчитается сама, а предложение соврёт, и никто этого не заметит:
 *  слова не выглядят числами и мимо любого поиска по цифрам проходят молча.
 *
 *  Этот тест — единственное место, где слово связано с числом. Он не даёт
 *  расхождению случиться тихо: рисунок и текст на одном экране, и читатель
 *  пересчитывает типы и ячейки глазами за две секунды.
 *
 *  Числа демо из абзаца ушли вместе с тиками (бриф, раздел 5) — пара
 *  `['демо', 'demos']` в этом тесте больше не проверяется.
 *
 *  Текст правится только владельцем. Если тест покраснел — значит поменялись
 *  ДАННЫЕ, и решение принимает владелец: либо текст переписывается под новое
 *  число, либо число неверно. Молча подгонять любую из сторон нельзя. */
const WORD_TO_NUMBER: Record<string, number> = {
  один: 1, два: 2, две: 2, три: 3, четыре: 4, пять: 5, шесть: 6,
  семь: 7, восемь: 8, девять: 9, десять: 10, одиннадцать: 11,
  двенадцать: 12, тринадцать: 13, двадцать: 20, тридцать: 30,
};

/** «тридцать две» → 32. Составные числительные записаны через пробел. */
function wordsToNumber(phrase: string): number | null {
  const parts = phrase.toLowerCase().trim().split(/\s+/);
  let sum = 0;
  for (const part of parts) {
    const value = WORD_TO_NUMBER[part];
    if (value === undefined) return null;
    sum += value;
  }
  return sum > 0 ? sum : null;
}

describe('тизер фабрики — слова абзаца не расходятся с числами рисунка', () => {
  const teaser = FACTORY_TEASER.text;

  it('словарь числительных сам себе не врёт', () => {
    expect(wordsToNumber('тридцать две')).toBe(32);
    expect(wordsToNumber('одиннадцать')).toBe(11);
    expect(wordsToNumber('четыре')).toBe(4);
    expect(wordsToNumber('пёстрый')).toBeNull();
  });

  it.each([
    ['тип', 'templates' as const],
    ['тем', 'themes' as const],
  ])('число перед «%s» совпадает с FACTORY_TOTALS', (noun, key) => {
    // Числительное — одно или два слова прямо перед существительным.
    const match = teaser.match(
      new RegExp(`([А-Яа-яЁё]+(?:\\s+[А-Яа-яЁё]+)?)\\s+(?:снятых\\s+)?${noun}`, 'i'),
    );
    expect(match, `в тексте тизера не нашлось числительного перед «${noun}»`)
      .not.toBeNull();

    const phrase = match![1];
    // Жадная группа могла прихватить соседнее слово — «одиннадцать снятых»
    // при тексте «одиннадцать снятых демо». Поэтому разбираем всю фразу, а
    // если не вышло — каждое слово по отдельности: числительное среди них
    // ровно одно, остальные словарю неизвестны и дают null.
    const words = phrase.split(/\s+/);
    const parsed = wordsToNumber(phrase)
      ?? words.map((w) => wordsToNumber(w)).find((n) => n !== null)
      ?? null;

    expect(
      parsed,
      `«${phrase}» не разобралось в число — словарь неполон, дополни его`,
    ).not.toBeNull();
    expect(
      parsed,
      `текст тизера говорит «${phrase} ${noun}», а данные — ${FACTORY_TOTALS[key]}. `
        + 'Расходятся текст и рисунок на одном экране: правит владелец, не реализация.',
    ).toBe(FACTORY_TOTALS[key]);
  });
});
