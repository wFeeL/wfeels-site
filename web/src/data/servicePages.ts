export function servicePage(slug: string): ServicePage {
  const page = SERVICE_PAGES.find((p) => p.slug === slug);
  if (!page) {
    throw new Error(`data/servicePages.ts: страницы услуги со slug «${slug}» нет.`);
  }
  return page;
}

// -------------------------------------------------------------- сторожа --
// Как в `data/process.ts` и `data/pricingShowcase.ts` — не тесты, а `throw`
// на уровне модуля: пустая секция или битая ссылка на прайс не могут
// попасть в сборку молча (08, раздел 7.3).

if (SERVICE_PAGES.length !== 9) {
  throw new Error(`data/servicePages.ts: ожидалось девять страниц услуг, а их ${SERVICE_PAGES.length}.`);
}

{
  const codes = SERVICE_PAGES.map((p) => p.code);
  const expected = Array.from({ length: 9 }, (_, i) => `S${i + 1}`);
  for (const code of expected) {
    if (!codes.includes(code)) {
      throw new Error(`data/servicePages.ts: нет записи с кодом «${code}».`);
    }
  }
  const dup = codes.find((c, i) => codes.indexOf(c) !== i);
  if (dup) {
    throw new Error(`data/servicePages.ts: код «${dup}» встречается дважды.`);
  }
}

for (const page of SERVICE_PAGES) {
  if (page.tiers.length < 1) {
    throw new Error(`data/servicePages.ts: у «${page.code}» нет ни одной ступени цены.`);
  }
  if (page.includes.length < 1) {
    throw new Error(`data/servicePages.ts: у «${page.code}» пуст список «Что входит».`);
  }
  if (page.excludes.length < 1) {
    throw new Error(`data/servicePages.ts: у «${page.code}» пуст список «Что не входит».`);
  }
  if (page.faq.length !== 3) {
    throw new Error(
      `data/servicePages.ts: у «${page.code}» ${page.faq.length} вопросов FAQ — ожидалось ровно три.`,
    );
  }
  const heroInTiers = page.tiers.some(
    (t) => t.group === page.heroTier.group && t.entry === page.heroTier.entry,
  );
  if (!heroInTiers) {
    throw new Error(
      `data/servicePages.ts: heroTier «${page.heroTier.group} → ${page.heroTier.entry}» ` +
      `у «${page.code}» не входит в собственный tiers.`,
    );
  }
  for (const t of page.tiers) {
    // Ступень уже проверена помощником `tier()` выше в момент построения
    // записи — здесь достаточно убедиться, что timeframe/timeframeSource
    // присутствуют или отсутствуют только вместе.
    if ((t.timeframe === undefined) !== (t.timeframeSource === undefined)) {
      throw new Error(
        `data/servicePages.ts: у ступени «${t.entry}» страницы «${page.code}» ` +
        'timeframe и timeframeSource заданы не вместе.',
      );
    }
  }
}
