  lead: string;
  /** Строка «Кому» — дословно из SERVICES.md. */
  audience: string;
  /** Срок услуги целиком, дословно из SERVICES.md (без «ё»). */
  term: string;
  /** Строка SERVICES.md, откуда взят term. */
  termSource: string;
  includes: readonly SourcedItem[];
  excludes: readonly SourcedItem[];
  /** Строка под списком «Что входит». Сегодня только у S5. */
