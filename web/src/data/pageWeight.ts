// Вес страницы против медианы — единственный источник для двух мест на
// главной: подписи под иллюстрацией «Замер» в блоке кейса «Этот сайт»
// (`components/home/Cases.astro`) и самой иллюстрации (`CaseWeightIllustration
// .astro`, задача 3 плана). До правки 2026-08-13 оба числа жили в
// `data/proof.ts` вместе с текстом снятой секции 6 «Что можно проверить»
// (D-030, `70-workshop/specs/site-v3/02-case-illustrations.md`, раздел 3.2) —
// секция удалена, но числа обязаны остаться на главной: `check-budget.mjs`
// сверяет их с фактическим весом собранной страницы и падает при
// расхождении больше 5%.
//
// Оба числа — одно зарегистрированное значение на каждое: подпись и рисунок
// читают отсюда, не дублируют его текстом.

/** Вес `index.html` в КБ — измерено `node scripts/check-budget.mjs` на
 *  готовой сборке. Подставляется вручную последним шагом задачи (раздел 3.2
 *  брифа, пункт 3): после подстановки гейт прогоняется ещё раз. */
export const PAGE_WEIGHT_KB = 410;

/** Медиана полного веса страницы по HTTP Archive — 2 412 КБ, десктоп.
 *
 *  Первоисточник: Web Almanac 2025, глава Page Weight, 50-й процентиль,
 *  обход июля 2025 — https://almanac.httparchive.org/en/2025/page-weight
 *  Проверено 2026-08-13. Мобильная медиана там же — 2 164 КБ; берётся
 *  десктопная, потому что сравнение идёт с десктопной сборкой этой страницы.
 *
 *  До 2026-08-13 здесь стояло «2,5 МБ» без ссылки и без даты. Число завышало
 *  медиану на 4% — то есть льстило нашему же сравнению. На странице, весь
 *  тезис которой «каждое число проверяемо», ошибка в свою пользу хуже любой
 *  другой: она превращает довод в рекламу. */
export const TYPICAL_PAGE_KB = 2412;

/** Слова кратности 1..13 — тот же список, что в `check-budget.mjs:369-370`,
 *  чтобы подпись и гейт не могли разойтись в написании числа словом. */
const MULTIPLIER_WORDS = [
  '', '', 'два', 'три', 'четыре', 'пять', 'шесть', 'семь',
  'восемь', 'девять', 'десять', 'одиннадцать', 'двенадцать', 'тринадцать',
] as const;

/** Та же медиана, округлённая до десятых мегабайта — ровно в том виде, в
 *  каком её читает человек на странице. Второго литерала «2,4» в тексте
 *  утверждения нет: до правки 2026-08-13 одно и то же число жило в трёх
 *  местах (здесь, в тексте и в гейте) и при первом же уточнении источника
 *  разошлось бы молча. */
const TYPICAL_MB_ROUNDED = Math.round(TYPICAL_PAGE_KB / 102.4) / 10;

/** Медиана словами для текста страницы: «2,4», а не «2.4». */
export const TYPICAL_PAGE_MB_TEXT = TYPICAL_MB_ROUNDED.toFixed(1).replace('.', ',');

/** Медиана в КБ, выведенная из ОКРУГЛЁННОГО «2,4», а не из точных 2412 —
 *  то самое число, которое фактически напечатано на странице как «2,4 МБ» и
 *  которое читает `check-budget.mjs:396` (`medianClaim`, `× 1024`) при сверке
 *  кратности. Иллюстрация «Замер» (`CaseWeightIllustration.astro`) считает
 *  длину полосы сравнения от ЭТОГО числа, а не от точных 2412: длина полосы
 *  обязана совпадать с тем же соотношением, которое подтверждает гейт,
 *  иначе полоса и подпись «в шесть раз больше» разошлись бы на видимую
 *  глазом величину при почти одинаковых на слух числах. */
export const TYPICAL_PAGE_KB_DISPLAY = TYPICAL_MB_ROUNDED * 1024;

/** Кратность выводится из веса на сборке, а не пишется числом. Считается от
 *  ОКРУГЛЁННОЙ медианы — от той самой, что напечатана на странице, а не от
 *  точных 2 412 КБ: иначе гейт, который читает число с готовой страницы, и
 *  этот модуль в редком случае округлили бы кратность в разные стороны и
 *  дали бы красноту на ровном месте. */
export const WEIGHT_MULTIPLIER = Math.round((TYPICAL_MB_ROUNDED * 1024) / PAGE_WEIGHT_KB);

if (!MULTIPLIER_WORDS[WEIGHT_MULTIPLIER]) {
  throw new Error(
    `data/pageWeight.ts: нет словесной формы для кратности ${WEIGHT_MULTIPLIER} — ` +
    'добавь слово в MULTIPLIER_WORDS или пересчитай вес.',
  );
}

/** Словесная кратность — «семь», не «7»: разметка несёт число словом
 *  (`02-texts.md`, секция 6, дословный текст). */
export const WEIGHT_MULTIPLIER_WORD = MULTIPLIER_WORDS[WEIGHT_MULTIPLIER];

/** Предложение целиком — дословно из `02-texts.md`, секция 6, «Сколько
 *  весит эта страница». Регулярка гейта (`check-budget.mjs:352`) ищет
 *  «весит N КБ» строчными и без флага `i` — писать заглавную «Весит» здесь
 *  запрещено, иначе сторож перестанет видеть утверждение. */
export const WEIGHT_CLAIM =
  `Она весит ${PAGE_WEIGHT_KB} КБ. Типичный сайт в интернете — ${TYPICAL_PAGE_MB_TEXT} МБ, ` +
  `в ${WEIGHT_MULTIPLIER_WORD} раз больше.`;

