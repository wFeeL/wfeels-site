// `LINK_LABEL` («ПОЛНАЯ ЗАГРУЗКА ПРИ 10 МБИТ/С») здесь БОЛЬШЕ НЕТ. Правка
// владельца 2026-08-21 сняла подпись условия замера с рисунка: «Убираем
// надпись „ПОЛНАЯ ЗАГРУЗКА ПРИ 10 МБИТ/С“». Решение осознанное и принято
// владельцем — времена 0,362 с и 1,976 с остаются на рисунке без названного
// канала; вписывать канал в подписи клеток вместо снятой строки запрещено.

// ---------------------------------------------------------------------
// Английские формы тех же чисел.
//
// Число одно, а записывается двумя способами: «0,4» и «0.4». Разделитель
// дробной части — не оформление, а орфография языка, и русская запятая на
// английской странице читается как разделитель разрядов, то есть меняет
// число в тысячу раз. Поэтому вместе с текстом переводится и она.
//
// Единицы тоже подписи, а не значения: «КБ» → «KB», «МБ» → «MB», «с» → «s».
// Сами величины не пересчитываются никуда — 481 КБ и 481 KB это одни и те же
// байты.
// ---------------------------------------------------------------------

import { type Locale } from '../i18n/locales';

/** Дробное число словами языка страницы. Русская форма получается той же
 *  заменой точки на запятую, что стоит в константах выше, — второго правила
 *  для одного и того же числа не заводится. */
export function decimalText(value: number, locale: Locale, digits = 1): string {
  const fixed = value.toFixed(digits);
  return locale === 'ru' ? fixed.replace('.', ',') : fixed;
}

/** Английские числительные той же таблицы 2…12. Список параллелен
 *  `MULTIPLIER_WORDS`: кратность, выпавшая из таблицы, обязана ронять сборку
 *  на обоих языках одинаково, а не печатать цифру вместо слова на одном из
 *  них. */
const MULTIPLIER_WORDS_EN: Readonly<Record<number, string>> = {
  2: 'twice',
  3: 'three times',
  4: 'four times',
  5: 'five times',
  6: 'six times',
  7: 'seven times',
  8: 'eight times',
  9: 'nine times',
  10: 'ten times',
  11: 'eleven times',
  12: 'twelve times',
};

if (Object.keys(MULTIPLIER_WORDS_EN).join() !== Object.keys(MULTIPLIER_WORDS).join()) {
  throw new Error(
    'data/pageWeight.ts: таблицы числительных разошлись. Кратность, у которой ' +
    'есть слово на одном языке и нет на другом, уронит сборку одной версии ' +
    'страницы и молча пройдёт на второй.',
  );
}

/* «в шесть раз легче» / «six times lighter» собирает `weightMultiplierPhrase`
   ниже — по весу СВОЕЙ страницы-хозяина, кем бы она ни была. Отдельной
   константы под английскую фразу здесь нет намеренно: она замораживала бы
   кратность одной версии в тексте другой, а веса у версий (и у хозяев) разные.

   Решение D-122 (раздел 4.6 брифа страниц кейсов, правка 3) обобщило обе
   функции ниже с «кратность ГЛАВНОЙ по языку» на «кратность ЛЮБОЙ страницы
   по её весу»: до этой правки `weightMultiplier` принимала `locale` и сама
   искала вес через `pageWeightKb`, что делало её непригодной для страницы
   кейса — свести кратность кейса можно было только копией той же формулы
   со своим весом внутри, то есть вторым источником истины. Теперь вес
   передаётся явно, и один и тот же расчёт обслуживает и главную, и кейс.

   Английское `twice` не берёт слова `times` — это не исключение из правила, а
   само правило языка, поэтому число словами хранится в таблице целиком. */

export function weightMultiplierPhrase(weightKb: number, locale: Locale): string {
  const value = weightMultiplier(weightKb);
  const table = locale === 'ru' ? MULTIPLIER_WORDS : MULTIPLIER_WORDS_EN;
  const word = table[value];
  if (word === undefined) {
    throw new Error(
      `data/pageWeight.ts: кратность ×${value} (${locale}) вне таблицы числительных ` +
      '(2…12). Либо вес страницы ушёл за пределы, на которые рассчитан рисунок, ' +
      'либо сломан расчёт — молча печатать цифру вместо слова нельзя.',
    );
  }
  if (locale === 'ru') {
    const times = value >= 2 && value <= 4 ? 'раза' : 'раз';
    return `в ${word} ${times} легче`;
  }
  return `${word} lighter`;
}

/** Вес главной на языке страницы. Оба числа — замеры гейта, ни одно не
 *  выведено из другого. */
export function pageWeightKb(locale: Locale): number {
  return locale === 'ru' ? PAGE_WEIGHT_KB : PAGE_WEIGHT_KB_EN;
}

/** Кратность для явно переданного веса страницы-хозяина — выводится из
 *  ЭТОГО веса, а не берётся у главной и не привязана к языку. Слово рядом с
 *  цифрой выводится из того же числа (`weightMultiplierPhrase`), поэтому
 *  разойтись они не могут. Вызывающая сторона сама решает, чей вес передать
 *  (`pageWeightKb(locale)` для главной, `CASE_PAGE_WEIGHT_KB` для страницы
 *  кейса `site-v3`) — эта функция самого решения не принимает. */
export function weightMultiplier(weightKb: number): number {
  return Math.round((TYPICAL_MB_ROUNDED * 1024) / weightKb);
}

