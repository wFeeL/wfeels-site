export const OUR_LOAD_SECONDS_TEXT_EN = decimalText(OUR_LOAD_SECONDS, 'en');
export const TYPICAL_LOAD_SECONDS_TEXT_EN = decimalText(TYPICAL_LOAD_SECONDS, 'en');
