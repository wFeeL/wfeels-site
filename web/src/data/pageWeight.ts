// Время загрузки. Два числа рисунка, и добыты они РАЗНЫМИ способами — это
// не оговорка, а устройство: своё время замерено, чужое выведено. Обе
// величины называют одну и ту же метрику на одном и том же канале, иначе
// сравнивать было бы нечего.
//
// Строка мелких метрик («N,N КБ JS · N сторонних скриптов») со 2026-08-19 с
// рисунка снята вместе со своими константами: композиция владельца от этого
// числа четыре — время и вес, наши и чужие. Числа не «потерялись»: их больше
// нет на странице, а `check-budget.mjs` по-прежнему печатает сжатый вес JS и
// число сторонних скриптов в своей сводке. Правило «число без сторожа на
// рисунок не попадает» этим не ослаблено — ослабило бы его обратное: число
// на рисунке без сторожа.
// ---------------------------------------------------------------------

/** Канал, на котором названы ОБА времени, — именованная константа, а не
 *  магическое число внутри формулы ниже. Без названного канала «0,4 с» — не
 *  число, а впечатление: та же страница даёт 0,048 с на 100 Мбит/с и 1,56 с
 *  на 3 Мбит/с (замер 2026-08-20, разброс в тридцать раз).
 *
 *  Правка владельца 2026-08-21 сняла подпись канала с самого рисунка
 *  (`LINK_LABEL`, стояла ниже) — «убираем надпись „ПОЛНАЯ ЗАГРУЗКА ПРИ
 *  10 МБИТ/С“». Решение осознанное: времена 0,362 с и 1,976 с остаются на
 *  рисунке без названного канала. Константа НЕ снята — она по-прежнему
 *  задаёт канал расчёта `TYPICAL_LOAD_SECONDS` ниже, только больше не
 *  печатается. */
export const LINK_MBPS = 10;

/** Наше время — ЗАМЕР, а не расчёт. Медиана девяти прогонов, 2026-08-20:
 *  `loadEventEnd` собранной страницы, headless Chromium 1440×900, кэш пуст,
 *  локальный статический сервер с gzip на html/css/js/svg, троттлинг CDP
 *  `Network.emulateNetworkConditions` — 10 Мбит/с, RTT 40 мс. Разброс
 *  0,349…0,409 с.
 *
 *  Печатается округлённым до десятых (`OUR_LOAD_SECONDS_TEXT` → «0,4 с»), а
 *  хранится замером: округление принадлежит показу, а не факту.
 *
 *  Воспроизведение того же замера на `astro preview` этого репозитория
 *  (2026-08-20, прогон сторожа ниже): 0,323…0,351 с, медиана 0,347 — то есть
 *  напечатанное «0,4» не льстит странице, а слегка её занижает. Так и должно
 *  быть: на странице, весь тезис которой «каждое число проверяемо», ошибка в
 *  свою пользу хуже любой другой.
 *
 *  Сторож — `src/tests/e2e/case-weight-load-time.spec.ts`: он воспроизводит
 *  этот замер на собранной странице и сверяет медиану с числом, НАПЕЧАТАННЫМ
 *  на рисунке. Прочитать число из этого модуля он не может по устройству
 *  (тест ходит в браузер, а не в исходники) — и не должен: сверять напечатанное
 *  с фактом и есть его работа. */
export const OUR_LOAD_SECONDS = 0.362;

/** Наше время в том виде, в каком его читает человек: «0,4», а не «0.362». */
export const OUR_LOAD_SECONDS_TEXT = OUR_LOAD_SECONDS.toFixed(1).replace('.', ',');

/** Чужое время — ВЫВОД, а не замер, и в коде это обязано быть видно:
 *  медиана веса × 8 бит ÷ скорость канала. 2 412 КБ на 10 Мбит/с даёт 1,976 с.
 *  RTT и время сервера в вывод не входят — вывод намеренно занижает чужое
 *  время, а не завышает: сравнение не должно льстить нашей стороне.
 *
 *  Вывод подтверждён замером (2026-08-20, тот же стенд, что у нашего времени):
 *  три страницы ровно по 2 412 КБ с разным составом — «медиа», «маркетинг»,
 *  «SPA» — дали полную загрузку 1,981 / 1,977 / 2,030 с, разброс по составу
 *  1,4 %. Именно поэтому на рисунке названа ПОЛНАЯ ЗАГРУЗКА, а не LCP: LCP при
 *  том же весе гулял от 0,97 до 12,04 с — в двенадцать раз, и любое его
 *  значение было бы авторским выбором, а не замером. */
export const TYPICAL_LOAD_SECONDS = (TYPICAL_PAGE_KB * 1024 * 8) / (LINK_MBPS * 1_000_000);

/** Чужое время для страницы: «2,0», а не «1.976». */
export const TYPICAL_LOAD_SECONDS_TEXT = TYPICAL_LOAD_SECONDS.toFixed(1).replace('.', ',');

// `LINK_LABEL` («ПОЛНАЯ ЗАГРУЗКА ПРИ 10 МБИТ/С») здесь БОЛЬШЕ НЕТ. Правка
// владельца 2026-08-21 сняла подпись условия замера с рисунка: «Убираем
// надпись „ПОЛНАЯ ЗАГРУЗКА ПРИ 10 МБИТ/С“». Решение осознанное и принято
// владельцем — времена 0,362 с и 1,976 с остаются на рисунке без названного
// канала; вписывать канал в подписи клеток вместо снятой строки запрещено.
