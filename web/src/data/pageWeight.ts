// Вес страницы против медианы — единственный источник для двух мест на
// главной: подписи под иллюстрацией «Замер» в блоке кейса «Этот сайт»
// (`components/home/Cases.astro`) и самой иллюстрации (`CaseWeightIllustration
// .astro`, задача 3 плана). До правки 2026-08-13 оба числа жили в
// `data/proof.ts` вместе с текстом снятой секции 6 «Что можно проверить»
// (D-030, `70-workshop/specs/site-v3/02-case-illustrations.md`, раздел 3.2) —
// секция удалена, но числа обязаны остаться на главной: `check-budget.mjs`
// сверяет их с фактическим весом собранной страницы и падает при
// расхождении больше 5%.
//
// Оба числа — одно зарегистрированное значение на каждое: подпись и рисунок
// читают отсюда, не дублируют его текстом.

/** Вес `index.html` в КБ — измерено `node scripts/check-budget.mjs` на
 *  готовой сборке. Подставляется вручную последним шагом задачи (раздел 3.2
 *  брифа, пункт 3): после подстановки гейт прогоняется ещё раз. */
export const PAGE_WEIGHT_KB = 397;

/** Медиана HTTP Archive — 2,5 МБ, в КБ (`02-texts.md`, секция 6; та же
 *  константа зашита в `scripts/check-budget.mjs:371`). */
export const TYPICAL_PAGE_KB = 2.5 * 1024;

/** Слова кратности 1..13 — тот же список, что в `check-budget.mjs:369-370`,
 *  чтобы подпись и гейт не могли разойтись в написании числа словом. */
const MULTIPLIER_WORDS = [
  '', '', 'два', 'три', 'четыре', 'пять', 'шесть', 'семь',
  'восемь', 'девять', 'десять', 'одиннадцать', 'двенадцать', 'тринадцать',
] as const;

/** Кратность выводится из веса на сборке, а не пишется числом — гейт
 *  (`check-budget.mjs:371`) считает её тем же способом и сверяет со словом
 *  на странице. */
export const WEIGHT_MULTIPLIER = Math.round(TYPICAL_PAGE_KB / PAGE_WEIGHT_KB);

if (!MULTIPLIER_WORDS[WEIGHT_MULTIPLIER]) {
  throw new Error(
    `data/pageWeight.ts: нет словесной формы для кратности ${WEIGHT_MULTIPLIER} — ` +
    'добавь слово в MULTIPLIER_WORDS или пересчитай вес.',
  );
}

/** Словесная кратность — «семь», не «7»: разметка несёт число словом
 *  (`02-texts.md`, секция 6, дословный текст). */
export const WEIGHT_MULTIPLIER_WORD = MULTIPLIER_WORDS[WEIGHT_MULTIPLIER];

/** Предложение целиком — дословно из `02-texts.md`, секция 6, «Сколько
 *  весит эта страница». Регулярка гейта (`check-budget.mjs:352`) ищет
 *  «весит N КБ» строчными и без флага `i` — писать заглавную «Весит» здесь
 *  запрещено, иначе сторож перестанет видеть утверждение. */
export const WEIGHT_CLAIM =
  `Она весит ${PAGE_WEIGHT_KB} КБ. Типичный сайт в интернете — 2,5 МБ, ` +
  `в ${WEIGHT_MULTIPLIER_WORD} раз больше.`;
