// Мелкие метрики строки под полосой сравнения (иллюстрация «Замер», задача
// 2 захода 2026-08-13). Правило задачи: «любое число на странице обязано
// иметь машинного сторожа» — оба сторожа живут в `check-budget.mjs` рядом с
// проверкой веса и кратности выше, тем же приёмом (число на странице
// сверяется с фактом на собранной странице, а не берётся на веру).
