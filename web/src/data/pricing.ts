/** Одна ступень услуги или позиция поддержки, дословно из PRICING.md. */
export interface PriceEntry {
  /** Название ступени/позиции — дословно из PRICING.md. */
  name: string;
  /** Что входит — дословно из PRICING.md, только у ступеней услуг («Ступени
   *  услуг» → Сайты/Боты и Mini Apps/ИИ/Backend и автоматизация). У строк
   *  раздела «Поддержка и доработка» этой колонки в PRICING.md нет — null. */
  whatIncluded: string | null;
  /** Цена «от», как есть в PRICING.md: с разделителями тысяч и словом «от»,
   *  либо словесная формулировка вроде «считать индивидуально». Часы сюда не
   *  попадают никогда — они не публикуются на сайте (спека 02-home, раздел 7:
   *  часы — обещание про будущее, которое не измерено). */
  price: string;
  /** Справочная цена в долларах по курсу 80 ₽/$ (см.
   *  `USD_REFERENCE_RATE` ниже), округлённая до целого доллара. Только
   *  ориентир для будущей английской страницы — русская страница доллар не
   *  показывает. `null`, если `price` не сводится к ровно одному рублёвому
   *  числу (текстовая формулировка или несколько чисел в одной строке
   *  PRICING.md — генератор не угадывает, какое из них основное). */
  priceUsdReference: number | null;
  /** Примечание — дословно из PRICING.md, только у строк раздела «Поддержка
   *  и доработка». У ступеней услуг этой колонки нет — null. */
  note: string | null;
  /** Раздел и строка PRICING.md, откуда взята запись — для сверки и для
   *  теста внутренней целостности этого файла. */
  source: string;
}

