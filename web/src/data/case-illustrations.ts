// ---------------------------------------------------------------------
// Иллюстрация 1 — «Замер» (кейс «Этот сайт», бриф раздел 3). Композиция —
// две сравнительные полосы (эта страница / медиана рынка) плюс строка
// мелких метрик под ними — решение владельца 2026-08-13 (диспетч задачи
