// ---------------------------------------------------------------------
// Иллюстрация 3 — «Пример диалога» (кейс «ИИ-консультант», бриф раздел 5).
// Сценарий клиента: бот отвечает покупателю груминг-салона (решение
// владельца 2026-08-13). Салон безымянный — выдуманные названия
// организаций запрещены (00-overview, раздел 7).
// ---------------------------------------------------------------------
export type DialogueRole = 'visitor' | 'bot';

export interface DialogueLine {
  role: DialogueRole;
  text: string;
  /** Чип источника — только у ответа с опорой на материалы (первая пара). */
  source?: string;
}

/** Метка поля — «пример» снимает утверждение о настоящем внедрении, а
 *  безымянный «салон» не создаёт несуществующей организации (бриф, 5.2). */
export const DIALOGUE_FIELD_LABEL = 'ПРИМЕР ДИАЛОГА · МАТЕРИАЛЫ ГРУМИНГ-САЛОНА';

/** Подсказка строки ввода — дословно, три точки, как написал владелец
 *  (`70-workshop/specs/site-v3/04-cases-brief.md`, раздел 4.6/11). Живёт
 *  константой здесь, а не строкой в разметке `CaseDialogueIllustration.astro`. */
export const DIALOGUE_INPUT_PLACEHOLDER = 'Напишите сообщение...';

/** Ровно четыре реплики, чередующиеся посетитель/бот/посетитель/бот. Текст
 *  этого захода (см. отчёт задачи 5 плана) — новый текст сайта, ещё не
 *  утверждённый владельцем построчно (бриф, раздел 5.3, «Вопросы
 *  владельцу», пункт 1). Правки сюда, а не в разметку компонента. */
export const DIALOGUE_LINES: readonly DialogueLine[] = [
  {
    role: 'visitor',
    text: 'Можно записать шпица на стрижку в выходные?',
  },
  {
    role: 'bot',
    text: 'По субботам салон работает. Записаться — у администратора.',
    source: 'КАК ЗАПИСАТЬСЯ',
  },
  {
    role: 'visitor',
    text: 'А чипирование делают?',
  },
  {
    role: 'bot',
    text: 'В материалах салона этого нет — лучше спросить администратора.',
  },
];

// ---------------------------------------------------------------------
// Сторожа инвариантов — падают на сборке, а не в проде (бриф, раздел 2.5).
// ---------------------------------------------------------------------
if (FLOW_SOURCES.length !== 3) {
  throw new Error('data/case-illustrations.ts: иллюстрация 2 несёт ровно три источника.');
}
if (DELIVERY_CHANNELS.length !== 4) {
  throw new Error('data/case-illustrations.ts: иллюстрация 2 несёт ровно четыре канала доставки.');
}
if (/google|sheets|bitrix|amocrm|битрикс|амоцрм/i.test(DELIVERY_CHANNELS.map((c) => c.label).join(' '))) {
  throw new Error(
    'data/case-illustrations.ts: канал доставки назван чужим сервисом — запрещено ' +
    '(README.md:105 — это вебхук и CSV-файл, а не интеграция с конкретным продуктом).',
  );
}
if (DIALOGUE_LINES.length !== 4) {
  throw new Error('data/case-illustrations.ts: иллюстрация 3 несёт ровно четыре реплики.');
}
DIALOGUE_LINES.forEach((line, i) => {
  const expectedRole: DialogueRole = i % 2 === 0 ? 'visitor' : 'bot';
  if (line.role !== expectedRole) {
    throw new Error(
      `data/case-illustrations.ts: реплика ${i} — «${line.role}», ожидалась ` +
      `«${expectedRole}» (реплики обязаны чередоваться посетитель/бот).`,
    );
  }
});
if (DIALOGUE_LINES.some((line) => /[0-9₽]/.test(line.text))) {
  throw new Error(
    'data/case-illustrations.ts: в выдуманном диалоге не может быть числа — его нечем ' +
    'проверить (бриф, раздел 5.3).',
  );
}
if (!/нет/i.test(DIALOGUE_LINES[3].text)) {
  throw new Error(
    'data/case-illustrations.ts: вторая реплика бота обязана оставаться честным отказом ' +
    '(бриф, раздел 5.3) — иначе консультант ничем не отличается от выдумывающего.',
  );
}
