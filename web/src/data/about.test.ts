import { describe, it, expect } from 'vitest';
import {
  ABOUT_PHOTO, ABOUT_LEAD, ABOUT_BLOCKS, ABOUT_CLOSING, ABOUT_CLIENT_LABEL,
} from './about';
import { splitBrandText, stripBrandMarkers } from '../lib/brandMarkers';

describe('about.ts — внутренняя целостность', () => {
  it('фото задано с шириной, высотой и alt', () => {
    expect(ABOUT_PHOTO.src).toBe('/wfeels-photo.jpg');
    expect(ABOUT_PHOTO.width).toBeGreaterThan(0);
    expect(ABOUT_PHOTO.height).toBeGreaterThan(0);
    expect(ABOUT_PHOTO.alt.length).toBeGreaterThan(0);
  });

  // Формулировка подписи — правка ВЛАДЕЛЬЦА (пункт 15 списка правок
  // 2026-08-14, ответ 2026-08-18, вопрос 1 брифа `04-sections-brief.md`):
  // числительное цифрой, без глагола «делаю». Сторож обновлён вместе с
  // самой правкой, не задним числом.
  it('лид — правка владельца от 2026-08-18 (пункт 15): «3 года», без «делаю»', () => {
    expect(ABOUT_LEAD).toBe(
      'Даниил. 3 года на Python, сайты и автоматизацию для малого бизнеса.',
    );
    expect(ABOUT_CLOSING).toContain('Каждое число на этом сайте');
  });

  // Главный сторож секции: оба абзаца — текст ВЛАДЕЛЬЦА от 2026-08-19,
  // и сверяется он целиком, посимвольно, а не по ключевым словам. Иначе
  // повторится ровно тот дефект, ради которого правка и делалась: раскладку
  // секции поменяли, а тексты остались от 2026-08-11, и никакая проверка
  // «содержит подстроку» этого не заметила.
  //
  // Сверяется строка БЕЗ маркеров значков (`{claude}` и прочие) — то самое
  // предложение, которое человек читает на странице. Литералы ниже — копия
  // сообщения владельца, их можно сличить с ним глазами.
  it('абзац 1 — дословно текст владельца от 2026-08-19 (инструменты)', () => {
    expect(ABOUT_BLOCKS).toHaveLength(2);
    expect(stripBrandMarkers(ABOUT_BLOCKS[0])).toBe(
      'Код пишу при помощи Claude Code, дизайн составляю в Figma и переношу '
      + 'на сайт через ChatGPT. Архитектуру, безопасность и проверку кода '
      + 'оставляю за собой. Именно с помощью таких инструментов я добиваюсь '
      + 'максимальной скорости в разработке продуктов.',
    );
  });

  it('абзац 2 — дословно текст владельца от 2026-08-19 (бизнес)', () => {
    expect(stripBrandMarkers(ABOUT_BLOCKS[1])).toBe(
      'Два года вел зоосервис в Москве: были разработаны 3 Telegram-бота, '
      + 'полноценный Telegram Mini App с онлайн-записью и Postgres база '
      + 'данных. Вся работа фиксировалась и сопровождалась при помощи GitHub '
      + '— любой разработчик сможет изучить контекст изменений и '
      + 'адаптироваться под проект.',
    );
  });

  // Места под значки стоят в обоих абзацах, каждое по одному разу и в
  // порядке предложения: три в первом (Claude, Figma, ChatGPT) и два во
  // втором (Postgres, GitHub — правка владельца 2026-08-20). Сторож нужен
  // потому, что маркер легко потерять при правке текста — а потерянный
  // значок молча исчезает со страницы, ничего не ломая.
  it('места под значки — три в первом абзаце и два во втором, в порядке предложения', () => {
    const marksOf = (text: string) =>
      splitBrandText(text)
        .filter((p) => p.kind === 'mark')
        .map((p) => (p.kind === 'mark' ? p.name : ''));
    expect(marksOf(ABOUT_BLOCKS[0])).toEqual(['claude', 'figma', 'chatgpt']);
    expect(marksOf(ABOUT_BLOCKS[1])).toEqual(['postgres', 'github']);
  });

  it('формулировка происхождения бизнеса — без имени, ровно «зоосервис в Москве» (D-011)', () => {
    expect(ABOUT_CLIENT_LABEL).toBe('зоосервис в Москве');
    expect(ABOUT_BLOCKS[1]).toContain(ABOUT_CLIENT_LABEL);
  });

  it('прошедшее время — «вел», а не настоящее «сопровождаю»', () => {
    expect(ABOUT_BLOCKS[1]).toMatch(/Два года вел /);
    expect(/сопровождаю\b/i.test(ABOUT_BLOCKS[1])).toBe(false);
  });

  // Решение владельца: на сайте вместо «ё» пишется «е». В этих двух абзацах
  // её нет ни одной — сторож ловит возврат «ё» при любой будущей правке.
  it('в обоих абзацах нет буквы «ё»', () => {
    expect(ABOUT_BLOCKS.join(' ')).not.toMatch(/[ёЁ]/);
  });

  it('никаких сумм в секции — ни 112 000 ₽, ни любой другой', () => {
    const all = ABOUT_LEAD + ABOUT_BLOCKS.join(' ') + ABOUT_CLOSING;
    expect(all).not.toContain('112 000');
    expect(all).not.toMatch(/₽/);
  });
});
