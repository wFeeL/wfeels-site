import { describe, it, expect } from 'vitest';
import { HERO_TERMS, CHECKED_AT } from './terms';

/* `terms.ts` — ручной файл (см. шапку самого файла), в отличие от
 * `pricing.ts`. Этот тест не читает 10-offer/PRICING.md — сайт отдельный
 * репозиторий и обязан собираться и без базы знаний рядом (тот же принцип,
 * что у `pricing.test.ts`) — а проверяет внутреннюю целостность: у каждой
 * записи есть `source`, порядок и состав совпадают с таблицей первого экрана
 * (спека 02-texts.md, секция 1).
 *
 * Правка 2026-08-28 (D-099): до этой даты три из четырёх строк ссылались на
 * SERVICES.md, а не на прайс — сайт показывал не те сроки. Теперь `source`
 * обязан ссылаться ИСКЛЮЧИТЕЛЬНО на PRICING.md — это единственная в этом
 * репозитории проверка направления «сайт цитирует прайс», доступная без
 * генератора (у сроков его нет, см. шапку `terms.ts`); дословное совпадение с
 * актуальным текстом файла база сверяет только при ручной проверке
 * `CHECKED_AT`, как и раньше. */

describe('terms.ts — внутренняя целостность', () => {
  it('дата сверки задана и в формате YYYY-MM-DD', () => {
    expect(CHECKED_AT).toMatch(/^\d{4}-\d{2}-\d{2}$/);
  });

  it('ровно четыре строки, в порядке таблицы первого экрана', () => {
    expect(HERO_TERMS.map((t) => t.label)).toEqual([
      'Сайты и лендинги',
      'Автоматизация и интеграции',
      'ИИ-консультант',
      'Аудит сайта',
    ]);
  });

  it('у каждой записи source ссылается на PRICING.md — не на SERVICES.md', () => {
    // До 2026-08-28 три из четырёх строк ссылались на SERVICES.md — сайт
    // показывал сроки услуг, а не прайса (D-099: сроки берутся только из
    // PRICING.md, как и цены). Сторож держит это направление закрытым.
    for (const entry of HERO_TERMS) {
      expect(entry.source, `«${entry.label}» без source`).toMatch(/^PRICING\.md:\d+/);
    }
  });

  it('срок набран в форме «от N[–N] дня/дней», а не голым диапазоном', () => {
    for (const entry of HERO_TERMS) {
      expect(entry.term, `«${entry.label}»: «${entry.term}»`).toMatch(/^от \d+(–\d+)? (дня|дней)$/);
    }
  });

  it('ни одна строка не задвоена', () => {
    const labels = HERO_TERMS.map((t) => t.label);
    expect(new Set(labels).size).toBe(labels.length);
  });
});
