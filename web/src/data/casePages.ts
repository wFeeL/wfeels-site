export function caseNarrative(caseSlug: string): CaseNarrative {
  const narrative = CASE_NARRATIVES[caseSlug];
  if (!narrative) {
    throw new Error(`data/casePages.ts: для опубликованного кейса «${caseSlug}» нет разбора.`);
  }
  return narrative;
}

/* Связи намеренно узкие: только прямое совпадение предмета кейса и услуги.
 * SlotBook не участвует — для него пока нет опубликованной страницы и
 * подтверждённого описания, из которого можно было бы вывести связь. */
const SERVICE_SLUGS_BY_CASE: Readonly<Record<string, readonly string[]>> = {
  'site-v3': ['website'],
  storefront: ['telegram-miniapp'],
  websites: ['website'],
  'ai-consultant': ['ai-consultant'],
  'zayavka-hub': ['integrations'],
};

const SERVICE_LINKS = SERVICE_GROUPS.flatMap((group) => group.links).map((link) => ({
  slug: link.href.replace('/services/', ''),
  href: link.href,
  title: link.text,
}));

export function caseServiceLinks(caseSlug: string): CaseServiceLink[] {
  const slugs = SERVICE_SLUGS_BY_CASE[caseSlug] ?? [];
  return slugs.map((slug) => {
    const service = SERVICE_LINKS.find((item) => item.slug === slug);
    if (!service) {
      throw new Error(
        `data/casePages.ts: кейс «${caseSlug}» ссылается на неизвестную услугу «${slug}».`,
      );
    }
    return service;
  });
}

export function casesForService(serviceSlug: string): PublishedCase[] {
  return publishedCases().filter((item) => (
    (SERVICE_SLUGS_BY_CASE[item.slug] ?? []).includes(serviceSlug)
  ));
}

export function caseGallerySlides(caseSlug: string): readonly CaseGallerySlide[] {
  /* Detail-страница не повторяет интерактивную галерею главной целиком:
   * каждый `<img>` — ресурс первой страницы для весового гейта. Берём
   * подтверждённые репрезентативные кадры, а полный набор остаётся в
   * `/case-galleries.json` для домашней галереи. */
  if (caseSlug === 'storefront') {
    return [STOREFRONT_SLIDES[0], STOREFRONT_SLIDES[3], STOREFRONT_SLIDES[6]];
  }
  if (caseSlug === 'websites') {
    return [WEBSITE_SLIDES[0], WEBSITE_SLIDES[6]];
  }
  return [];
}

export function publishedCaseHref(item: PublishedCase): string {
  return caseHref(item.slug);
}
